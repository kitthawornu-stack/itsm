/**
 * หาไบต์กำพร้าในที่เก็บไฟล์ — **ตัดสินอย่างเดียว ไม่ลบเอง**
 *
 * วัดจริงในฐานข้อมูลพัฒนา: 849 วัตถุใน MinIO แต่มีแถวไฟล์แนบเพียง 5 แถว ·
 * ส่วนต่างคือไบต์ที่ไม่มีอะไรชี้ถึง สะสมจากเทสต์ที่ลบแถวตรง ๆ โดยไม่ผ่าน
 * `deleteAttachment` และจากการลบไฟล์ที่ล้มแล้วถูกกลืนไว้โดยตั้งใจ
 *
 * ผลเสียสองอย่างที่ต่างกัน: **ดิสก์โตไม่มีที่สิ้นสุดโดยไม่มีใครเห็น** และ
 * **PDPA — "ลบข้อมูลแล้ว" ที่ไฟล์ยังอยู่ ไม่ใช่การลบ**
 *
 * ตัวเก็บกวาดที่ตัดสินผิดจะลบไฟล์แนบจริงของผู้ใช้ ซึ่งไม่มีที่ไหนให้กู้ ·
 * ไฟล์นี้จึงเป็นฟังก์ชันบริสุทธิ์ ไม่แตะที่เก็บไฟล์ ไม่แตะฐานข้อมูล
 * ไม่อ่านนาฬิกา
 */

/**
 * อายุขั้นต่ำก่อนจะถือว่ากำพร้า
 *
 * ตอนอัปโหลด ไบต์ถูกเขียนก่อนที่แถวจะได้ `storageKey` (กติกา "จองก่อนทำ") ·
 * ระหว่างสองขั้นนั้นไฟล์ดู "ไม่มีใครชี้ถึง" ทั้งที่กำลังถูกใช้งานอยู่ ·
 * หนึ่งวันเผื่อไว้กว้างมากเมื่อเทียบกับช่องว่างจริงที่เป็นมิลลิวินาที —
 * **ราคาของการเผื่อมากไปคือขยะอยู่นานขึ้นหนึ่งวัน ราคาของการเผื่อน้อยไป
 * คือไฟล์ของผู้ใช้หายถาวร**
 */
export const MIN_AGE_MS = 24 * 60 * 60 * 1000;

export interface ObjectRef {
  key: string;
  lastModified: Date | null;
  sizeBytes: number;
}

export interface OrphanPlan {
  /** ไฟล์ที่ไม่มีแถวชี้ถึงและเก่าพอ */
  orphans: ObjectRef[];
  orphanBytes: number;
  /** ไฟล์ที่มีแถวชี้ถึง — นับไว้เพื่อพิสูจน์ว่าการเทียบทำงานจริง */
  matched: number;
  /** ไฟล์ที่ยังใหม่เกินกว่าจะตัดสิน */
  tooYoung: number;
  /** ไฟล์ที่ไม่รู้เวลาที่เขียน — ถือว่าใหม่ */
  unknownAge: number;
  /**
   * ลบได้หรือยัง
   *
   * `false` เมื่อสัญญาณบ่งชี้ว่าข้อมูลฝั่งฐานข้อมูลอาจไม่ครบ · ผู้เรียก
   * ต้องไม่ลบอะไรเลยในกรณีนั้น
   */
  safeToDelete: boolean;
  /** เหตุผลที่ยังลบไม่ได้ · `null` = ลบได้ */
  refusedReason: string | null;
}

/**
 * เทียบไบต์ที่มีอยู่กับคีย์ที่ฐานข้อมูลรู้จัก
 *
 * @param objects ทุกวัตถุใน bucket
 * @param knownKeys `storageKey` ทุกค่าที่มีแถวอยู่จริง
 * @param now เวลาที่ใช้ตัดสินอายุ — **ส่งเข้ามาเสมอ ไม่อ่านเอง**
 */
export function planOrphanCleanup(
  objects: readonly ObjectRef[],
  knownKeys: ReadonlySet<string>,
  now: Date,
): OrphanPlan {
  const orphans: ObjectRef[] = [];
  let matched = 0;
  let tooYoung = 0;
  let unknownAge = 0;

  for (const o of objects) {
    if (knownKeys.has(o.key)) {
      matched += 1;
      continue;
    }
    /*
      **ไม่รู้เวลาที่เขียน ถือว่าใหม่** — การถือว่าเก่าคือการลบไฟล์ที่เราไม่รู้
      อะไรเกี่ยวกับมันเลย ซึ่งเป็นการเดาที่กู้ไม่ได้ถ้าเดาผิด
    */
    if (o.lastModified === null) {
      unknownAge += 1;
      continue;
    }
    if (now.getTime() - o.lastModified.getTime() < MIN_AGE_MS) {
      tooYoung += 1;
      continue;
    }
    orphans.push(o);
  }

  /*
    **เซ็ตว่างจากฐานข้อมูล ต้องไม่แปลว่า "ทุกอย่างกำพร้า"**

    ถ้าคิวรีล้ม เขียนผิด หรือถูกกรองด้วย tenant ที่ผิด ผลลัพธ์คือลบทั้ง bucket ·
    เป็นกติกาเดียวกับที่ใช้กับสิทธิ์: รายการที่ใช้กรองว่างเปล่า ต้องแปลว่า
    ไม่เห็นอะไรเลย ไม่ใช่เห็นทุกอย่าง (CLAUDE.md)

    bucket ที่ว่างจริง ๆ ไม่เข้าเงื่อนไขนี้ เพราะไม่มีอะไรจะลบอยู่แล้ว
  */
  const refusedReason =
    knownKeys.size === 0 && objects.length > 0
      ? 'ฐานข้อมูลไม่คืนคีย์ของไฟล์แนบเลยสักตัว ทั้งที่ที่เก็บไฟล์มีของอยู่ — ' +
        'อาจอ่านฐานข้อมูลไม่สำเร็จ · ไม่ลบอะไรทั้งสิ้น'
      : null;

  return {
    orphans,
    orphanBytes: orphans.reduce((sum, o) => sum + o.sizeBytes, 0),
    matched,
    tooYoung,
    unknownAge,
    safeToDelete: refusedReason === null,
    refusedReason,
  };
}
