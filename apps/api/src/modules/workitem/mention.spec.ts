/**
 * การกล่าวถึงในความเห็น — เทสต์เป็นข้อกำหนด
 *
 * ฟังก์ชันบริสุทธิ์ล้วน จึงทดสอบเคส "เมื่อไรจะไม่ส่ง" ได้ครบ ซึ่งเป็นเคสส่วนใหญ่
 * และเป็นเคสที่พลาดแล้วเงียบ
 *
 * **ข้อที่สำคัญที่สุด: ชื่อต้องปรากฏในข้อความจริง** — หน้าจอส่งรายการ id มา
 * ถ้าเซิร์ฟเวอร์เชื่อตรง ๆ ใครก็ส่ง id ใครก็ได้มาพร้อมข้อความที่ไม่มีชื่อเขา
 * แล้วคนคนนั้นได้แจ้งเตือนว่า "ถูกเรียกถึง" แต่เปิดเข้าไปหาไม่เจอว่าใครเรียก
 * — การแจ้งเตือนชนิดนี้จะเชื่อถือไม่ได้ทั้งชนิด และคนจะเลิกอ่านมัน
 */
import { describe, expect, it } from 'vitest';

import { mentionMarkerCount, mentionsIn } from './mention';

const somchai = { userId: 1n, displayName: 'สมชาย ใจดี' };
const wipa = { userId: 2n, displayName: 'วิภา ทองคำ' };

describe('A · ชื่อต้องอยู่ในข้อความจริง', () => {
  it('**id ที่ส่งมาโดยไม่มีชื่อในข้อความ ต้องถูกทิ้ง**', () => {
    /*
      เคสที่ทั้งไฟล์นี้มีไว้เพื่อดัก · ถ้าปล่อยผ่าน คนที่ไม่ได้ถูกเรียกจะได้
      แจ้งเตือนว่าถูกเรียก แล้วเปิดเข้าไปหาไม่เจอว่าใครเรียกและเรื่องอะไร
    */
    expect(mentionsIn('ช่วยดูให้หน่อยครับ', [somchai])).toEqual([]);
    expect(mentionsIn('@คนอื่น ช่วยดูหน่อย', [somchai])).toEqual([]);
  });

  it('ชื่อที่อยู่ในข้อความ ผ่าน', () => {
    expect(mentionsIn('@สมชาย ใจดี ช่วยดูให้หน่อย', [somchai])).toEqual([somchai]);
  });

  it('ไม่มี `@` เลย = ไม่มีการกล่าวถึง แม้ชื่อจะอยู่ในข้อความ', () => {
    // การพูดถึงชื่อคนในประโยค ไม่ใช่การเรียกเขา
    expect(mentionsIn('เรื่องนี้สมชาย ใจดี เคยทำไว้', [somchai])).toEqual([]);
  });

  it('เรียกหลายคนได้ และเรียกคนเดิมซ้ำได้ใบเดียว', () => {
    const out = mentionsIn('@สมชาย ใจดี กับ @วิภา ทองคำ ช่วยดู @สมชาย ใจดี อีกที', [
      somchai,
      wipa,
      somchai,
    ]);
    expect(out.map((m) => m.userId)).toEqual([1n, 2n]);
  });

  it('ชื่อว่างเปล่าถูกข้าม ไม่ใช่ตรงกับทุกข้อความ', () => {
    /*
      `body.includes('@' + '')` เป็นจริงเสมอเมื่อข้อความมี `@` · ถ้าไม่กัน
      ผู้ใช้ที่ชื่อว่าง (ข้อมูลนำเข้าที่ไม่สมบูรณ์) จะถูกเรียกทุกครั้งที่ใครพิมพ์ @
    */
    expect(mentionsIn('@ใครสักคน', [{ userId: 9n, displayName: '   ' }])).toEqual([]);
  });
});

describe('B · ชื่อไทยที่มีช่องว่าง', () => {
  it('เทียบตรงตัว ไม่ตัดที่ช่องว่าง', () => {
    /*
      ชื่อคนไทยมีช่องว่างระหว่างชื่อกับนามสกุล · ถ้าตัดคำแล้วจับทีละคำ
      "@สมชาย" จะไปตรงกับ "สมชาย ใจดี" และ "สมชาย รักงาน" พร้อมกัน
      แล้วคนผิดได้รับแจ้งเตือนโดยที่ไม่มีใครสังเกต
    */
    const other = { userId: 3n, displayName: 'สมชาย รักงาน' };
    expect(mentionsIn('@สมชาย ใจดี ดูหน่อย', [somchai, other])).toEqual([somchai]);
  });

  it('ชื่อที่เป็นส่วนหนึ่งของอีกชื่อ — ตรงทั้งคู่ตามที่เขียนจริง', () => {
    /*
      "@สมชาย ใจดีมาก" มีสตริง "@สมชาย ใจดี" อยู่ข้างใน · ยอมรับตามความจริง
      ของการเทียบสตริง และหน้าจอเป็นคนเลือกจากรายการ ไม่ได้พิมพ์เอง
      — บันทึกไว้ให้รู้ ไม่ใช่แกล้งว่าไม่มี
    */
    expect(mentionsIn('@สมชาย ใจดีมาก', [somchai])).toEqual([somchai]);
  });
});

describe('C · นับ `@` ในข้อความ', () => {
  it('บอกได้ว่าพิมพ์ @ กี่จุด เพื่อเตือนเมื่อส่งถึงไม่ครบ', () => {
    /*
      "พิมพ์ @ ไว้ 2 จุด แต่ส่งถึงได้ 1 คน" ต้องบอกคนเขียน · เงียบไปเฉย ๆ
      ทำให้เขาเชื่อว่าอีกคนได้รับแล้ว แล้วรอคำตอบที่ไม่มีวันมา
    */
    expect(mentionMarkerCount('@สมชาย ใจดี และ @วิภา ทองคำ')).toBe(2);
    expect(mentionMarkerCount('ไม่มีใครถูกเรียก')).toBe(0);
  });
});
