/**
 * รูปแบบไฟล์ CSV ที่ระบบใช้ — **แหล่งความจริงเดียว**
 *
 * อยู่ใน `@itsm/types` เพราะทั้ง api (ผู้ใช้กดดาวน์โหลด) และ worker
 * (ส่งตามตารางเวลา) ต้องผลิตไฟล์หน้าตาเดียวกัน · worker เรียกโค้ดของ api
 * ไม่ได้ (คนละแอป) · **ถ้าเขียนซ้ำสองที่ จะกลายเป็นสองความจริงเรื่อง
 * "ไฟล์ที่ส่งออกหน้าตาอย่างไร"** แล้วไฟล์จากสองทางจะต่างกันโดยไม่มีใครเห็น
 * จนกว่าจะมีคนเอาสองไฟล์มาเทียบกัน
 */

/**
 * คอลัมน์ของไฟล์ · **ชุดเดียวทั้งขาเข้าและขาออก**
 *
 * ไฟล์ที่ระบบส่งออก ต้องนำเข้ากลับได้ทันทีโดยไม่ต้องแก้หัวตาราง —
 * มิฉะนั้นการส่งออกแล้วนำเข้าใหม่ (ซึ่งเป็นวิธีแก้ข้อมูลจำนวนมากที่คนใช้จริง)
 * จะพังโดยไม่มีใครบอกล่วงหน้า
 */
export const CSV_COLUMNS = [
  'externalKey',
  'summary',
  'status',
  'priority',
  'reporterEmail',
] as const;

export type ExportRow = Record<(typeof CSV_COLUMNS)[number], string>;

/** อักขระที่ทำให้ Excel ตีความค่าเป็นสูตรเมื่อมันอยู่ตัวแรก */
const FORMULA_LEADS = ['=', '+', '-', '@'];

/**
 * ค่าหนึ่งช่อง เตรียมให้พร้อมวางลงไฟล์
 *
 * ครอบด้วยคำพูดเมื่อมีจุลภาค คำพูด หรือการขึ้นบรรทัดใหม่ · คำพูดในค่ากลาย
 * เป็นคำพูดซ้อนสองตัว ตามที่ `parseCsv` อ่าน
 */
export function csvCell(value: string): string {
  /*
    **ค่าที่ขึ้นต้นด้วย `=` `+` `-` `@` คือสูตรในสายตา Excel**

    หัวข้องานที่ผู้ใช้พิมพ์ กลายเป็นคำสั่งที่ Excel รันตอนเปิดไฟล์ได้ ·
    นำหน้าด้วยคำพูดเดี่ยว ซึ่ง Excel อ่านว่า "บังคับให้เป็นข้อความ"
    และไม่แสดงในเซลล์ · ค่าถูกแก้จริง จึงต้องเห็นได้ตอนอ่านกลับ
    ไม่ใช่แก้เงียบ ๆ แล้วบอกว่าเหมือนเดิม
  */
  const looksLikeFormula = FORMULA_LEADS.some((c) => value.startsWith(c));
  const guarded = looksLikeFormula ? `'${value}` : value;

  /*
    ค่าที่ถูกกันไว้เพราะเหมือนสูตร **ครอบด้วยคำพูดเสมอ** แม้ไม่มีอักขระที่
    บังคับให้ครอบ · คำพูดเดี่ยวอย่างเดียวพอกัน Excel แล้ว แต่การครอบด้วย
    ทำให้เจตนา "ช่องนี้คือข้อความ" อ่านออกจากตัวไฟล์เอง ไม่ต้องรู้กติกา
    ของ Excel ก่อนจึงจะเข้าใจ
  */
  if (!looksLikeFormula && !/[",\r\n]/.test(guarded)) return guarded;
  return `"${guarded.replace(/"/g, '""')}"`;
}

/**
 * ทั้งไฟล์
 *
 * **ขึ้นต้นด้วย BOM เสมอ** — Excel เปิดไฟล์ UTF-8 ที่ไม่มี BOM ด้วย codepage
 * ของเครื่อง ภาษาไทยจึงกลายเป็นขยะทั้งไฟล์ โดยที่ไฟล์ยังเปิดได้และไม่มี error
 * · คนที่เจอจะสรุปว่าข้อมูลในระบบเสีย ไม่ใช่ว่าไฟล์ถูกอ่านผิด
 *
 * ไม่มีแถวเลยก็ยังได้หัวตาราง — ไฟล์เปล่าอธิบายตัวเองไม่ได้ว่ามันคือไฟล์อะไร
 */
export function toCsv(rows: readonly ExportRow[]): string {
  const lines = [CSV_COLUMNS.join(',')];
  for (const r of rows) lines.push(CSV_COLUMNS.map((c) => csvCell(r[c])).join(','));
  // CRLF — Excel บนวินโดวส์คาดแบบนี้ และ `parseCsv` รองรับทั้งสองแบบอยู่แล้ว
  return `﻿${lines.join('\r\n')}\r\n`;
}
