/**
 * ข้อกำหนดของการส่งออก CSV — **เขียนก่อนโค้ด**
 *
 * ## ทำไมต้องมีไฟล์นี้
 *
 * เอกสารสถานะเขียนไว้เองว่าเครื่องมือย้ายข้อมูล "ยังเหลือการส่งออกทั้งองค์กร" ·
 * องค์กรที่เอาข้อมูลของตัวเองออกไม่ได้ คือองค์กรที่ถูกจับเป็นตัวประกัน
 * และเป็นข้อที่ลูกค้าองค์กรถามก่อนเซ็นเสมอ
 *
 * ## เกณฑ์ที่ทำให้มันเป็น "ส่งออก" ไม่ใช่ "ทิ้งข้อมูลกองหนึ่ง"
 *
 * **ไฟล์ที่ส่งออก ต้องนำเข้ากลับได้ด้วยตัวอ่านตัวเดียวกัน** — `parseCsv`
 * ที่ `csv-import.ts` ใช้อยู่จริง · ถ้าเขียนตัวอ่านของเทสต์ขึ้นมาเอง
 * เราจะพิสูจน์ได้แค่ว่าตัวเขียนกับตัวอ่านของเราเข้าใจตรงกัน ซึ่งไม่ได้แปลว่า
 * ระบบจริงอ่านมันได้ (CLAUDE.md: การตรวจต้องเทียบกับสภาพจริง ไม่ใช่กับ
 * คำกล่าวอ้างอีกท่อนของสิ่งเดียวกัน)
 *
 * ## สิ่งที่ผิดแล้วเงียบ
 *
 *   1. **ไม่มี BOM** — Excel เปิดไฟล์ UTF-8 ที่ไม่มี BOM ด้วย codepage
 *      ของเครื่อง ภาษาไทยกลายเป็นขยะทั้งไฟล์ · ไฟล์ยังเปิดได้ ไม่มี error
 *      คนจะคิดว่าข้อมูลในระบบเสีย ไม่ใช่ว่าไฟล์ถูกอ่านผิด
 *   2. **จุลภาคในหัวข้อ** — หัวข้องานภาษาไทยมีจุลภาคได้ตามปกติ
 *      ถ้าไม่ครอบด้วยคำพูด คอลัมน์จะเลื่อนทั้งแถวโดยที่ไฟล์ยัง "ถูกต้อง"
 *   3. **ขึ้นบรรทัดใหม่ในรายละเอียด** — ทำให้หนึ่งงานกลายเป็นหลายแถว
 *   4. **สูตรที่ Excel รัน** — ค่าที่ขึ้นต้นด้วย `=` `+` `-` `@` ถูก Excel
 *      ตีความเป็นสูตร · หัวข้อที่ผู้ใช้พิมพ์กลายเป็นคำสั่งได้
 */
import { describe, expect, it } from 'vitest';

import { parseCsv, planImport } from './csv-import';
import { EXPORT_COLUMNS, toCsv, csvCell } from './csv-export';

describe('ส่งออก CSV · A · หนึ่งช่อง', () => {
  it('ข้อความธรรมดาไม่ถูกครอบโดยไม่จำเป็น', () => {
    expect(csvCell('เครื่องพิมพ์เสีย')).toBe('เครื่องพิมพ์เสีย');
  });

  it('**จุลภาคต้องถูกครอบ** — ไม่งั้นคอลัมน์เลื่อนทั้งแถว', () => {
    expect(csvCell('ขอสิทธิ์, เร่งด่วน')).toBe('"ขอสิทธิ์, เร่งด่วน"');
  });

  it('**คำพูดในค่า ต้องกลายเป็นคำพูดซ้อนสองตัว**', () => {
    expect(csvCell('เครื่อง "ตัวที่สอง" เสีย')).toBe('"เครื่อง ""ตัวที่สอง"" เสีย"');
  });

  it('**ขึ้นบรรทัดใหม่ต้องถูกครอบ** — ไม่งั้นหนึ่งงานกลายเป็นหลายแถว', () => {
    expect(csvCell('บรรทัดแรก\nบรรทัดสอง')).toBe('"บรรทัดแรก\nบรรทัดสอง"');
  });

  /**
   * **ค่าที่ขึ้นต้นด้วย `=` `+` `-` `@` คือสูตรในสายตา Excel**
   *
   * หัวข้องานที่ผู้ใช้พิมพ์ว่า `=cmd|...` จะถูก Excel ตีความเป็นสูตร
   * เมื่อเปิดไฟล์ · นำหน้าด้วยเครื่องหมายคำพูดเดี่ยว ซึ่ง Excel อ่านเป็น
   * "บังคับให้เป็นข้อความ" และไม่แสดงในเซลล์
   */
  it('**ค่าที่ขึ้นต้นเหมือนสูตร ต้องถูกทำให้เป็นข้อความ**', () => {
    for (const lead of ['=', '+', '-', '@']) {
      const out = csvCell(`${lead}SUM(A1)`);
      expect(out.startsWith(`"'${lead}`), `${lead} ยังเป็นสูตรอยู่: ${out}`).toBe(true);
    }
  });

  it('ค่าว่างคือช่องว่าง ไม่ใช่คำว่า null', () => {
    expect(csvCell('')).toBe('');
  });

  /** ค่าที่มีเครื่องหมายลบอยู่กลาง ไม่ใช่สูตร — ห้ามเติมอะไรให้ */
  it('เครื่องหมายที่อยู่กลางค่า ไม่ใช่สูตร', () => {
    expect(csvCell('SD-1234')).toBe('SD-1234');
  });
});

describe('ส่งออก CSV · B · ทั้งไฟล์', () => {
  const rows = [
    {
      externalKey: 'SD-1',
      summary: 'เครื่องพิมพ์ชั้น 3 ไม่ยอมพิมพ์',
      status: 'ใหม่',
      priority: 'สูง',
      reporterEmail: 'somchai@company.co.th',
    },
    {
      externalKey: 'SD-2',
      summary: 'ขอสิทธิ์เข้าโฟลเดอร์บัญชี, เร่งด่วน',
      status: 'ปิดแล้ว',
      priority: '',
      reporterEmail: 'malee@company.co.th',
    },
  ];

  it('บรรทัดแรกคือหัวตาราง', () => {
    const first = toCsv(rows).replace(/^﻿/, '').split('\r\n')[0];
    expect(first).toBe(EXPORT_COLUMNS.join(','));
  });

  /**
   * **ด่านที่เทียบกับอีกฝั่งจริง ไม่ใช่กับตัวเอง**
   *
   * เคสข้างบนเทียบหัวตารางกับ `EXPORT_COLUMNS` ซึ่งเป็นค่าที่ตัวเขียนใช้เอง —
   * **สองฝั่งมาจากที่เดียวกัน** จึงผิดพร้อมกันได้โดยเขียว · พิสูจน์แล้ว:
   * เปลี่ยน `EXPORT_COLUMNS` ให้ตัด `reporterEmail` ทิ้ง แล้วทั้งไฟล์ยังเขียว
   * ทั้งที่ไฟล์ที่ส่งออกนำเข้ากลับไม่ได้แล้ว (CLAUDE.md: ตัวสแกนที่เทียบ
   * เอกสารกับตัวมันเอง ไม่ได้ตรวจอะไรเลย)
   *
   * เคสนี้จึงส่งไฟล์ที่ส่งออกเข้า `planImport` ตัวจริง แล้วยืนยันว่า
   * ไม่มีปัญหาระดับไฟล์ — ซึ่งคือคำถามที่เราอยากรู้จริง ๆ
   */
  it('**ไฟล์ที่ส่งออก ผ่านตัววางแผนนำเข้าตัวจริงโดยไม่มีปัญหาระดับไฟล์**', () => {
    const plan = planImport(parseCsv(toCsv(rows)), {
      statuses: ['ใหม่', 'ปิดแล้ว'],
      priorities: ['สูง'],
      emails: ['somchai@company.co.th', 'malee@company.co.th'],
    });
    const fileLevel = plan.problems.filter((p) => p.column === null);
    expect(fileLevel, JSON.stringify(fileLevel)).toEqual([]);
    expect(plan.problems, JSON.stringify(plan.problems)).toEqual([]);
    expect(plan.wouldImport).toBe(2);
  });

  /**
   * **BOM คือสิ่งเดียวที่ทำให้ Excel อ่านภาษาไทยถูก**
   *
   * ไม่มีมันแล้วไฟล์ยังเปิดได้ ไม่มี error — แค่ข้อความไทยกลายเป็นขยะทั้งไฟล์
   * และคนจะคิดว่าข้อมูลในระบบเสีย
   */
  it('**ขึ้นต้นด้วย BOM**', () => {
    expect(toCsv(rows).charCodeAt(0)).toBe(0xfeff);
  });

  it('ท้ายบรรทัดเป็น CRLF — Excel บนวินโดวส์คาดแบบนี้', () => {
    expect(toCsv(rows)).toContain('\r\n');
  });

  it('ไม่มีแถวเลย ยังต้องได้หัวตาราง — ไฟล์เปล่าอธิบายตัวเองไม่ได้', () => {
    const out = toCsv([]).replace(/^﻿/, '');
    expect(out.trim()).toBe(EXPORT_COLUMNS.join(','));
  });

  /**
   * **ด่านหลักของไฟล์นี้ — วนกลับได้จริง**
   *
   * อ่านกลับด้วย `parseCsv` ตัวเดียวกับที่ทางนำเข้าใช้จริง ไม่ใช่ตัวอ่าน
   * ที่เขียนขึ้นในเทสต์ · ถ้าเขียนเอง เราจะพิสูจน์ได้แค่ว่าตัวเขียนกับตัวอ่าน
   * ของเราเข้าใจตรงกัน ซึ่งไม่เกี่ยวกับว่าระบบจริงอ่านมันได้หรือไม่
   */
  it('**ไฟล์ที่ส่งออก อ่านกลับด้วยตัวอ่านของทางนำเข้าได้ครบทุกค่า**', () => {
    const parsed = parseCsv(toCsv(rows));
    expect(parsed.header).toEqual([...EXPORT_COLUMNS]);
    expect(parsed.rows).toHaveLength(2);
    expect(parsed.rows[1]?.values[1]).toBe('ขอสิทธิ์เข้าโฟลเดอร์บัญชี, เร่งด่วน');
    expect(parsed.rows[0]?.values[1]).toBe('เครื่องพิมพ์ชั้น 3 ไม่ยอมพิมพ์');
  });

  /**
   * **วนกลับได้แม้ค่าจะมีทุกอย่างที่ทำให้ CSV พัง**
   *
   * เคสข้างบนใช้ข้อมูลที่ "ดูปกติ" · เคสนี้ยัดจุลภาค คำพูด และการขึ้นบรรทัด
   * ใหม่เข้าไปพร้อมกัน ซึ่งเป็นสิ่งที่ข้อมูลจริงมีจริง
   */
  it('**วนกลับได้แม้มีจุลภาค คำพูด และขึ้นบรรทัดใหม่พร้อมกัน**', () => {
    const nasty = [
      {
        externalKey: 'SD-9',
        summary: 'หัวข้อ, มี "คำพูด"\nและขึ้นบรรทัดใหม่',
        status: 'ใหม่',
        priority: 'สูง',
        reporterEmail: 'a@b.co.th',
      },
    ];
    const parsed = parseCsv(toCsv(nasty));
    expect(parsed.rows).toHaveLength(1);
    expect(parsed.rows[0]?.values[1]).toBe('หัวข้อ, มี "คำพูด"\nและขึ้นบรรทัดใหม่');
  });

  /**
   * **ด่านพิสูจน์ว่าเคสวนกลับข้างบนแดงได้จริง**
   *
   * ถ้าตัวเขียนไม่ครอบค่าเลย เคสข้างบนต้องพัง · เคสนี้จำลองตัวเขียนแบบนั้น
   * แล้วยืนยันว่าผลที่อ่านกลับได้ **ไม่ตรง** — ถ้ามันยังตรง แปลว่าข้อมูล
   * ตัวอย่างอ่อนเกินกว่าจะจับอะไรได้ และเคสข้างบนไม่ได้พิสูจน์อะไรเลย
   */
  it('**ตัวเขียนที่ไม่ครอบค่า ต้องทำให้การวนกลับพังจริง**', () => {
    const naive = [
      EXPORT_COLUMNS.join(','),
      ['SD-9', 'หัวข้อ, มีจุลภาค', 'ใหม่', 'สูง', 'a@b.co.th'].join(','),
    ].join('\r\n');
    const parsed = parseCsv(naive);
    expect(parsed.rows[0]?.values[1], 'ตัวเขียนแบบไม่ครอบกลับอ่านถูก — ตัวอย่างอ่อนไป').not.toBe(
      'หัวข้อ, มีจุลภาค',
    );
  });

  /**
   * ค่าที่ถูกทำให้เป็นข้อความเพราะเหมือนสูตร ต้องอ่านกลับมาแล้ว **ยังเห็นว่า
   * ถูกเติมอะไรไว้** — ไม่ใช่หายไปเงียบ ๆ · คนที่นำเข้ากลับต้องรู้ว่าค่านี้
   * ไม่ตรงกับต้นฉบับเป๊ะ ซึ่งดีกว่าให้ Excel รันมันแล้วไม่มีใครรู้
   */
  it('ค่าที่เหมือนสูตร อ่านกลับแล้วยังตามรอยได้', () => {
    const parsed = parseCsv(
      toCsv([
        {
          externalKey: 'SD-9',
          summary: '=1+1',
          status: 'ใหม่',
          priority: '',
          reporterEmail: 'a@b.co.th',
        },
      ]),
    );
    expect(parsed.rows[0]?.values[1]).toBe("'=1+1");
  });
});
