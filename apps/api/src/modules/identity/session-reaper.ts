/**
 * เก็บกวาดเซสชันที่ตายแล้ว
 *
 * ตาราง `session` โตทุกครั้งที่มีคนล็อกอิน และไม่เคยเล็กลง ·
 * วัดจริงในฐานข้อมูลพัฒนา: **184 แถว หมดอายุแล้ว 169** และไม่มีอะไรลบมันเลย ·
 * ทุกคิวรีกรองด้วย `tokenHash` แถวตายจึงไม่เคยโผล่ที่ไหน — รูปแบบเดียวกับ
 * แถวกำพร้าใน `notification` ที่รั่ว 170 แถวโดยไม่มีใครเห็น
 *
 * ## ช่วงผ่อนผัน: ตารางนี้เป็นร่องรอยความปลอดภัยด้วย
 *
 * `userAgent` และ `ipAddress` เก็บไว้ให้เจ้าของบัญชีดูว่ามีเซสชันแปลกปลอมไหม ·
 * เซสชันที่เพิ่งหมดอายุคือ**หลักฐานเดียว**ว่ามีใครล็อกอินจากที่ไหนเมื่อวาน ·
 * ลบทิ้งทันทีที่หมดอายุ คือการทำลายหลักฐานก่อนที่ใครจะได้ดู
 *
 * ฟังก์ชันบริสุทธิ์ · "ตอนนี้" ส่งเข้ามาเสมอ
 */
import type { UtcDate } from '@itsm/types';

/**
 * เก็บเซสชันที่ตายแล้วไว้กี่วัน
 *
 * สามสิบวันพอให้เจ้าของบัญชีหรือผู้ดูแลย้อนดูได้ว่ามีการล็อกอินที่ผิดปกติไหม
 * **ค่านี้ควรทบทวนพร้อมกับนโยบายเก็บข้อมูลส่วนบุคคล (PDPA)** — เก็บนานเกิน
 * จำเป็นก็เป็นความเสี่ยงอีกแบบ
 */
export const SESSION_KEEP_DAYS = 30;

/**
 * ลบได้กี่แถวต่อรอบ
 *
 * `DELETE` ก้อนใหญ่ล็อกตารางนาน แล้วทุกคนล็อกอินไม่ได้ระหว่างนั้น ·
 * รอบถัดไปมาอีกใน 6 ชั่วโมง ค้างไว้บ้างไม่เป็นไร
 */
export const REAP_BATCH = 500;

const DAY_MS = 86_400_000;

export interface ReapableSession {
  id: bigint;
  expiresAt: Date;
  /** `null` = ยังไม่ถูกเพิกถอน */
  revokedAt: Date | null;
}

/**
 * เซสชันตายเมื่อไร
 *
 * **เร็วที่สุดระหว่างวันหมดอายุกับวันเพิกถอน** — ไม่ใช่วันเพิกถอนเสมอไป ·
 * ผู้ดูแลที่กดเพิกถอนเซสชันเก่าที่หมดอายุไปนานแล้ว ไม่ควรได้ช่วงผ่อนผันใหม่
 * ให้แถวนั้น · และเซสชันที่ถูกเพิกถอนตั้งแต่ปีที่แล้วแต่ตั้งวันหมดอายุไว้ไกล
 * ก็ไม่ควรค้างอยู่ตลอดกาล
 */
export function diedAt(s: ReapableSession): Date {
  if (s.revokedAt === null) return s.expiresAt;
  return s.revokedAt.getTime() < s.expiresAt.getTime() ? s.revokedAt : s.expiresAt;
}

/**
 * รายการ id ที่ลบได้ในรอบนี้
 *
 * เรียง **จากที่ตายนานที่สุดก่อน** — ไม่ใช่ลำดับที่ฐานข้อมูลบังเอิญคืนมา ·
 * ถ้าเรียงตามลำดับที่ได้มา รอบที่ชนเพดานทุกครั้งจะเก็บกวาดแถวชุดเดิมซ้ำ ๆ
 * แล้วแถวที่เก่าที่สุดอาจไม่เคยถูกแตะเลย
 */
export function reapable(
  rows: readonly ReapableSession[],
  now: UtcDate,
  keepDays: number = SESSION_KEEP_DAYS,
  batch: number = REAP_BATCH,
): bigint[] {
  const cutoff = now.getTime() - keepDays * DAY_MS;
  return rows
    .map((r) => ({ id: r.id, at: diedAt(r).getTime() }))
    // ครบพอดีถือว่าเลยแล้ว — ขอบเขตต้องตัดสินทางเดียว ไม่ใช่แล้วแต่วินาที
    .filter((r) => r.at <= cutoff)
    .sort((a, b) => a.at - b.at)
    .slice(0, batch)
    .map((r) => r.id);
}
