-- เก็บชื่อผู้ทำไว้ในแถว audit เอง
--
-- `audit_log.actor_id` เป็น `onDelete: SetNull` — ลบผู้ใช้เมื่อไร ร่องรอยทั้งหมด
-- ของคนนั้นจะกลายเป็น "ไม่มี actor" ซึ่ง **แยกจาก "ระบบทำเอง" ไม่ได้เลย**
-- ผู้ตรวจสอบจะอ่านได้ว่าระบบเปลี่ยนสิทธิ์เอง ทั้งที่จริงมีคนทำแต่ลาออกไปแล้ว
--
-- audit ที่ลืมว่าใครทำเมื่อบัญชีถูกลบ ไม่ใช่ audit — เก็บชื่อไว้ตอนเขียน
-- จึงเป็นการซ้ำข้อมูลโดยตั้งใจ (denormalise) ไม่ใช่ความผิดพลาด

ALTER TABLE `audit_log`
  ADD COLUMN `actor_name` VARCHAR(255) NULL;

-- เติมย้อนหลังให้แถวเดิมที่ actor ยังอยู่ · แถวที่ actor_id เป็น NULL อยู่แล้ว
-- ปล่อยไว้เป็น NULL เพราะเราไม่รู้จริง ๆ ว่าเป็นระบบทำเองหรือคนที่ถูกลบไปแล้ว
-- การเดาย้อนหลังจะสร้างข้อมูลที่ดูน่าเชื่อแต่ไม่มีอะไรรองรับ
UPDATE `audit_log` a
  JOIN `user` u ON u.id = a.actor_id
  SET a.actor_name = u.display_name;
