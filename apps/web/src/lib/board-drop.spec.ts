/**
 * ตำแหน่งที่การ์ดจะไปอยู่เมื่อปล่อยเมาส์ — เทสต์เป็นข้อกำหนด
 *
 * เป็นเทสต์ชุดแรกของ `apps/web` · ก่อนหน้านี้ script `test` ของ workspace นี้
 * เป็น `echo "no web tests yet"` ซึ่งเป็นกลไกที่ไม่มีอะไรเรียกใช้ในรูปแบบที่
 * เลวร้ายที่สุด — **CI เขียวเพราะไม่มีอะไรถูกตรวจ** (CLAUDE.md §4)
 *
 * สามข้อที่ต้องถูกตั้งแต่แรก:
 *
 *   1. **ตัดการ์ดที่กำลังลากออกก่อนหาเพื่อนบ้าน** — ไม่ตัดแล้วการลากลงข้างล่าง
 *      ในคอลัมน์เดิมจะได้เพื่อนบ้านผิดไปหนึ่งช่อง · ไม่โผล่ตอนลากขึ้นข้างบน
 *      หรือลากข้ามคอลัมน์ จึงผ่านการลองด้วยมือได้สบาย
 *   2. **ปล่อยที่เดิมต้องไม่เขียนอะไร** — ประวัติที่รกเท่ากับไม่มีประวัติ
 *   3. **ข้ามคอลัมน์ต้องส่ง `toColumn` · ในคอลัมน์เดิมต้องไม่ส่ง** — การส่ง
 *      `toColumn` ที่เท่ากับสถานะปัจจุบัน ทำให้เซิร์ฟเวอร์ไปหา transition
 *      ที่ไม่มีอยู่ แล้วปฏิเสธการเลื่อนลำดับธรรมดา
 */
import { describe, expect, it } from 'vitest';

import { planDrop, type DropColumn } from './board-drop';

const COLUMNS: DropColumn[] = [
  {
    statusId: '1',
    name: 'รอรับเรื่อง',
    cards: [{ itemKey: 'SD-1' }, { itemKey: 'SD-2' }, { itemKey: 'SD-3' }],
  },
  { statusId: '2', name: 'กำลังทำ', cards: [{ itemKey: 'SD-9' }] },
  { statusId: '3', name: 'ปิดแล้ว', cards: [] },
];

describe('A · ในคอลัมน์เดิม', () => {
  it('**ลากลงข้างล่าง — เพื่อนบ้านต้องไม่นับตัวเอง**', () => {
    /*
      SD-1 ปล่อยบน SD-3 · หลังตัด SD-1 ออก รายการเหลือ [SD-2, SD-3]
      ตำแหน่งที่จะแทรกคือก่อน SD-3 เพื่อนบ้านจึงเป็น SD-2 กับ SD-3

      ถ้าไม่ตัดตัวเองออก รายการยังเป็น [SD-1, SD-2, SD-3] ตำแหน่งของ SD-3
      คือ 2 เพื่อนบ้านบนกลายเป็น SD-2 เหมือนกันโดยบังเอิญ — แต่ **ลำดับที่
      รายงานผ่าน aria-live จะผิด** และเคสอื่นจะเพี้ยนตามไปด้วย
    */
    const plan = planDrop(COLUMNS, 'SD-1', 0, 'SD-3');
    expect(plan?.move).toEqual({ afterKey: 'SD-2', beforeKey: 'SD-3' });
    expect(plan?.say).toContain('อันดับ 2');
  });

  it('ลากลงล่างสุด — ต่อท้าย ไม่มีเพื่อนบ้านล่าง', () => {
    const plan = planDrop(COLUMNS, 'SD-1', 0, null);
    expect(plan?.move).toEqual({ afterKey: 'SD-3' });
    expect(plan?.say).toContain('อันดับ 3');
  });

  it('ลากขึ้นบนสุด — ไม่มีเพื่อนบ้านบน', () => {
    const plan = planDrop(COLUMNS, 'SD-3', 0, 'SD-1');
    expect(plan?.move).toEqual({ beforeKey: 'SD-1' });
    expect(plan?.say).toContain('อันดับ 1');
  });

  it('**ไม่ส่ง `toColumn` เมื่ออยู่คอลัมน์เดิม**', () => {
    /*
      ส่ง `toColumn` ที่เท่ากับสถานะปัจจุบัน ทำให้เซิร์ฟเวอร์ไปหาปุ่ม transition
      ที่ไม่มีอยู่ (ไม่มีใครทำปุ่ม "จากรอรับเรื่องไปรอรับเรื่อง") แล้วปฏิเสธ
      การเลื่อนลำดับธรรมดาด้วย 422 — ผู้ใช้จะเห็นว่าลากในคอลัมน์เดิมไม่ได้
    */
    expect(planDrop(COLUMNS, 'SD-1', 0, 'SD-3')?.move.toColumn).toBeUndefined();
  });
});

describe('B · ปล่อยที่เดิม', () => {
  it('**ปล่อยบนตัวเอง ต้องไม่เขียนอะไร**', () => {
    expect(planDrop(COLUMNS, 'SD-2', 0, 'SD-2')).toBeNull();
  });

  it('**ปล่อยบนใบที่อยู่ถัดลงไปหนึ่ง ก็คือที่เดิม**', () => {
    // SD-1 แทรกก่อน SD-2 = ตำแหน่งที่มันอยู่แล้ว · ต่างจากการปล่อยบนตัวเอง
    // แค่ตรงพิกัดเมาส์ ผลลัพธ์เหมือนกันทุกประการ
    expect(planDrop(COLUMNS, 'SD-1', 0, 'SD-2')).toBeNull();
  });

  it('ปล่อยท้ายคอลัมน์ ทั้งที่อยู่ท้ายอยู่แล้ว', () => {
    expect(planDrop(COLUMNS, 'SD-3', 0, null)).toBeNull();
  });
});

describe('C · ข้ามคอลัมน์', () => {
  it('**ส่งชื่อคอลัมน์ปลายทางไปด้วย**', () => {
    const plan = planDrop(COLUMNS, 'SD-1', 1, 'SD-9');
    expect(plan?.move).toEqual({ toColumn: 'กำลังทำ', beforeKey: 'SD-9' });
    expect(plan?.say).toBe('ย้าย SD-1 ไป กำลังทำ');
  });

  it('ปล่อยลงคอลัมน์ว่าง — ไม่มีเพื่อนบ้านทั้งสองข้าง', () => {
    expect(planDrop(COLUMNS, 'SD-1', 2, null)?.move).toEqual({ toColumn: 'ปิดแล้ว' });
  });

  it('ปล่อยลงคอลัมน์เดิมที่ตัวเองเป็นใบเดียว ไม่ต้องทำอะไร', () => {
    expect(planDrop(COLUMNS, 'SD-9', 1, null)).toBeNull();
  });
});

describe('D · ข้อมูลที่ไม่ตรง', () => {
  it('คอลัมน์ที่ไม่มีอยู่ ต้องไม่ทำอะไร ไม่ใช่โยน', () => {
    // กระดานอาจถูกวาดใหม่ระหว่างที่ผู้ใช้ลากค้างอยู่ · การโยนตรงนี้ทำให้
    // ทั้งหน้าจอพังเพราะการปล่อยเมาส์ครั้งเดียว
    expect(planDrop(COLUMNS, 'SD-1', 9, null)).toBeNull();
  });

  it('การ์ดที่หาไม่เจอในกระดาน ต้องไม่ทำอะไร', () => {
    expect(planDrop(COLUMNS, 'SD-999', 0, 'SD-1')).toBeNull();
  });

  it('เป้าหมายที่หาไม่เจอในคอลัมน์นั้น ต้องไม่ทำอะไร', () => {
    expect(planDrop(COLUMNS, 'SD-1', 0, 'SD-9')).toBeNull();
  });
});
