/**
 * Webhook — กติกาการส่งเหตุการณ์ออกไปหาระบบอื่น
 *
 * ฟังก์ชันบริสุทธิ์ทั้งไฟล์ · **ไม่ยิง HTTP เอง ไม่อ่านนาฬิกาเอง**
 * กติกาเดียวกับ SLA Engine — เคส "ปลายทางล่มสามวัน" ทดสอบได้ก็ต่อเมื่อ
 * เวลาส่งเข้ามา
 *
 * ## ใช้คำศัพท์เหตุการณ์ชุดเดียวกับ Automation
 *
 * `TriggerKind` มีอยู่แล้วห้าชนิดและมีที่ยิงจริงในระบบ · การสร้างคำศัพท์
 * คู่ขนานสำหรับ webhook จะทำให้สองรายการเพี้ยนคนละทางในวันที่มีคนเพิ่ม
 * เหตุการณ์ใหม่ที่เดียว — และฝั่งที่ไม่ได้เพิ่มจะเงียบ ไม่ใช่พัง
 */
import { createHmac, timingSafeEqual } from 'node:crypto';

import type { UtcDate } from '@itsm/types';

/** หัวข้อมูลที่ส่งไปกับคำขอ — ขึ้นต้น `X-` เพื่อไม่ชนกับหัวมาตรฐาน */
export const SIGNATURE_HEADER = 'X-Helix-Signature';
export const TIMESTAMP_HEADER = 'X-Helix-Timestamp';

/**
 * จำนวนครั้งที่ลองส่งทั้งหมด รวมครั้งแรก
 *
 * 5 ครั้งกับระยะห่างข้างล่างกินเวลาราวครึ่งชั่วโมง · นานพอให้ปลายทางที่
 * รีสตาร์ทกลับมาทัน และสั้นพอที่คนจะยังจำได้ว่าเมื่อกี้ทำอะไรไว้
 */
export const MAX_ATTEMPTS = 5;

/**
 * ปลายทางนี้สนใจเหตุการณ์นี้ไหม
 *
 * **รายการว่าง = ไม่สนใจอะไรเลย ไม่ใช่ "เอาหมด"** · กติกาเดียวกับสิทธิ์:
 * ข้อมูลที่ไม่ครบต้องแปลว่าไม่มี · ถ้าตีความว่าเอาหมด ปลายทางที่ตั้งไว้
 * ครึ่ง ๆ กลาง ๆ จะได้รับเหตุการณ์ชนิดใหม่ที่เพิ่มเข้าระบบภายหลัง
 * โดยไม่มีใครเคยตกลงว่าจะส่งให้
 */
export function isSubscribed(events: readonly string[], event: string): boolean {
  return events.includes(event);
}

/**
 * ลายเซ็นของคำขอ — HMAC-SHA256 เลขฐานสิบหก
 *
 * **เวลาอยู่ในสิ่งที่เซ็น ไม่ใช่แค่ส่งไปข้าง ๆ** · ถ้าเซ็นแต่เนื้อหา
 * คนที่ดักคำขอเก่าไว้ได้จะส่งซ้ำเมื่อไรก็ได้พร้อมเวลาใหม่ แล้วปลายทาง
 * ตรวจผ่าน — การผูกเวลาเข้ากับลายเซ็นทำให้เปลี่ยนเวลาแล้วลายเซ็นพัง
 *
 * ตัวคั่นเป็นจุด เพราะเวลาเป็นตัวเลขล้วน จึงไม่มีทางที่การเลื่อนขอบเขต
 * ระหว่างสองส่วนจะให้สตริงเดิม
 */
export function signPayload(secret: string, timestampMs: number, body: string): string {
  return createHmac('sha256', secret).update(`${String(timestampMs)}.${body}`).digest('hex');
}

/**
 * ตรวจลายเซ็น — เทียบแบบคงเวลา
 *
 * มีไว้ให้ปลายทางที่เป็นระบบของเราเองใช้ และให้เทสต์พิสูจน์ว่าลายเซ็นที่
 * ผลิตออกไปตรวจกลับได้จริง · การเทียบด้วย `===` บอกความยาวของส่วนที่ตรงกัน
 * ผ่านเวลาที่ใช้ ซึ่งพอจะเดาลายเซ็นทีละตัวอักษรได้
 */
export function verifySignature(
  secret: string,
  timestampMs: number,
  body: string,
  given: string,
): boolean {
  const expected = signPayload(secret, timestampMs, body);
  if (given.length !== expected.length) return false;
  return timingSafeEqual(Buffer.from(expected), Buffer.from(given));
}

/**
 * ล้มแบบนี้ควรลองใหม่ไหม
 *
 * `null` = ต่อไม่ติดเลย (ไม่มีรหัสสถานะ) ซึ่งคนละเรื่องกับปลายทางปฏิเสธ
 *
 * **4xx คือปลายทางปฏิเสธ ลองใหม่ก็ได้คำตอบเดิม** — และการลองซ้ำห้าครั้ง
 * คือการยิงคำขอที่รู้อยู่แล้วว่าจะล้ม ห้าครั้ง · ให้ล้มให้จบแล้วให้ผู้ดูแล
 * เห็นในรายการว่าปลายทางไหนปฏิเสธ · ยกเว้น 408 กับ 429 ซึ่งเป็น 4xx
 * ที่บอกตรง ๆ ว่า "ลองใหม่ทีหลัง"
 */
export function shouldRetry(status: number | null): boolean {
  if (status === null) return true;
  if (status === 408 || status === 429) return true;
  return status >= 500;
}

/**
 * ระยะห่างก่อนลองใหม่ — คงที่ ไม่มีการสุ่ม
 *
 * ไม่ใส่ jitter โดยตั้งใจ: ระบบนี้มีปลายทางไม่กี่รายการ ปัญหาการยิงพร้อมกัน
 * จึงไม่มีจริง · ส่วนค่าที่คงที่ทำให้ทดสอบได้ และทำให้ผู้ดูแลตอบได้ว่า
 * "ครั้งต่อไปกี่โมง" โดยไม่ต้องเปิดโค้ดดู
 */
/**
 * ระยะห่างก่อนลองใหม่ — เขียนเป็นบันไดตรง ๆ ไม่ใช้ดัชนีในอาร์เรย์
 *
 * เคยเขียนเป็นอาร์เรย์แล้วบีบดัชนี · `noUncheckedIndexedAccess` บังคับให้มี
 * ค่าสำรองท้ายนิพจน์ แล้ว **ค่าสำรองนั้นบังทั้งตัวบีบค่าติดลบและตัวคุมเพดาน**
 * — ลบทั้งสองอย่างทิ้งทีละอันแล้วเทสต์ยังเขียวทั้งคู่ เพราะค่าสำรองรับไว้แทน
 * พอดี (ด่านซ้อนกันแบบเดียวกับ `moveGadget` ใน CLAUDE.md)
 *
 * แบบนี้ไม่มีดัชนี จึงไม่มีค่าสำรอง และทุกสาขาเป็นการตัดสินใจจริงที่ลบแล้วแดง
 *
 * ไม่ใส่การสุ่ม (jitter) โดยตั้งใจ: ระบบนี้มีปลายทางไม่กี่รายการ ปัญหาการยิง
 * พร้อมกันจึงไม่มีจริง · ค่าที่คงที่ทำให้ทดสอบได้ และทำให้ผู้ดูแลตอบได้ว่า
 * "ครั้งต่อไปกี่โมง" โดยไม่ต้องเปิดโค้ดดู
 */
export function backoffMs(attempt: number): number {
  const n = Math.floor(attempt);
  if (n <= 1) return 30_000;
  if (n === 2) return 120_000;
  if (n === 3) return 300_000;
  // ครั้งที่สี่ขึ้นไปคงที่ — ปลายทางที่ล่มยาวต้องไม่ถูกเลื่อนไปเป็นวัน
  return 900_000;
}

/**
 * ครั้งต่อไปจะลองเมื่อไร — `null` เมื่อครบเพดานแล้ว
 *
 * "ตอนนี้" ส่งเข้ามา ไม่ใช่ให้อ่านนาฬิกาเอง
 */
export function nextAttemptAt(attemptsSoFar: number, now: UtcDate | Date): Date | null {
  if (attemptsSoFar >= MAX_ATTEMPTS) return null;
  return new Date(now.getTime() + backoffMs(attemptsSoFar));
}
