/**
 * การกล่าวถึงในความเห็น
 *
 * องค์กรมาจาก LINE ที่ `@` คือวิธีเรียกคน · ระบบตั๋วที่ไม่มีวิธีเรียกใครสักคน
 * ทำให้ทุกคำถามที่ต้องการคนเฉพาะเจาะจง ถูกยกกลับไปถามในแชท
 *
 * ## กติกาที่แปลกกว่าที่คิด: ชื่อต้องปรากฏในข้อความจริง
 *
 * หน้าจอส่งรายการ id มาพร้อมข้อความ · ถ้าเซิร์ฟเวอร์เชื่อรายการนั้นตรง ๆ
 * ใครก็ส่ง id ใครก็ได้มาพร้อมข้อความที่ไม่มีชื่อเขาอยู่เลย ผลคือคนคนนั้น
 * ได้แจ้งเตือนว่า "ถูกเรียกถึง" แล้วเปิดเข้าไปหาไม่เจอว่าใครเรียก
 *
 * นั่นไม่ใช่แค่กวน — มันทำให้การแจ้งเตือนชนิดนี้เชื่อถือไม่ได้ทั้งชนิด
 * และคนจะเลิกอ่านมันภายในไม่กี่สัปดาห์ · จึงตรวจว่า `@ชื่อ` อยู่ในข้อความจริง
 * ก่อนยอมรับ
 *
 * ฟังก์ชันบริสุทธิ์ล้วน — ทดสอบเคส "เมื่อไรจะไม่ส่ง" ได้โดยไม่ต้องมีฐานข้อมูล
 */

export interface MentionCandidate {
  userId: bigint;
  displayName: string;
}

/**
 * คัดเฉพาะคนที่ถูกกล่าวถึงในข้อความจริง
 *
 * @param body ข้อความที่ผู้ใช้พิมพ์
 * @param candidates คนที่หน้าจอบอกว่ากล่าวถึง **และผู้เรียกตรวจสิทธิ์มาแล้ว**
 *
 * การตรวจสิทธิ์ไม่ได้อยู่ที่นี่โดยตั้งใจ · ถ้าเอามารวม จะทดสอบเคส
 * "เมื่อไรจะไม่ส่ง" ไม่ได้เลย ซึ่งเป็นเคสส่วนใหญ่ (กติกาเดียวกับ `commentAudience`)
 */
export function mentionsIn(
  body: string,
  candidates: readonly MentionCandidate[],
): MentionCandidate[] {
  /*
    ทางลัด ไม่ใช่กฎ

    ลบบรรทัดนี้แล้วเทสต์ยังเขียวทุกเคส เพราะการเทียบ `@ชื่อ` รายคนข้างล่าง
    ครอบอยู่แล้ว · เก็บไว้เพราะความเห็นส่วนใหญ่ไม่มี `@` เลย และเส้นทางนี้
    ถูกเรียกทุกครั้งที่มีคนพิมพ์ความเห็น — **แต่ห้ามอ่านว่ามันกันอะไรอยู่**
    ถ้าวันหนึ่งกฎเปลี่ยนไปอิงอย่างอื่น บรรทัดนี้จะไม่ใช่ตัวที่ต้องแก้
  */
  if (!body.includes('@')) return [];
  const seen = new Set<string>();
  const out: MentionCandidate[] = [];
  for (const c of candidates) {
    const name = c.displayName.trim();
    if (name === '') continue;
    /*
      เทียบแบบตรงตัว ไม่ใช่ตัดช่องว่างหรือทำ normalize

      ชื่อคนไทยมีช่องว่างระหว่างชื่อกับนามสกุล และไม่มีคำว่า "คำ" ให้ตัด ·
      การพยายามจับชื่อจากข้อความเองด้วย regex จะได้ทั้งคนผิดและพลาดคนถูก
      · ที่นี่จึงถามว่า "ชื่อที่หน้าจอบอกว่าเรียก อยู่ในข้อความไหม" เท่านั้น
    */
    if (!body.includes(`@${name}`)) continue;
    const key = c.userId.toString();
    if (seen.has(key)) continue;
    seen.add(key);
    out.push(c);
  }
  return out;
}

/**
 * ชื่อที่ขึ้นต้นด้วย `@` ในข้อความ — สำหรับเตือนคนเขียนว่าเรียกใครไม่สำเร็จ
 *
 * **คืนแค่ตำแหน่งที่มี `@` ไม่ได้เดาว่าเป็นชื่อใคร** · ผู้เรียกเอาไปเทียบกับ
 * รายชื่อที่ยอมรับแล้ว เพื่อบอกได้ว่า "พิมพ์ @ ไว้ 2 จุด แต่ส่งถึงได้ 1 คน"
 * — เงียบไปเฉย ๆ ทำให้คนเขียนเชื่อว่าอีกคนได้รับแล้ว
 */
export function mentionMarkerCount(body: string): number {
  return (body.match(/@/g) ?? []).length;
}
