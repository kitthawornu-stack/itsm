/**
 * การไล่ผลกระทบใน CMDB — เทสต์เป็นข้อกำหนด เขียนก่อนโค้ด
 *
 * คำถามที่ CMDB มีไว้ตอบคือ **"ถ้าเครื่องนี้ล่ม อะไรพังตามบ้าง"** ·
 * คำตอบมาจากการไล่ความสัมพันธ์ "พึ่งพา" ต่อกันเป็นทอด ๆ ซึ่งเป็นที่ที่
 * พลาดแล้วเงียบที่สุดในทั้งระบบ:
 *
 *   1. **วงจรทำให้ไล่ไม่จบ** — A พึ่ง B, B พึ่ง C, C พึ่ง A เกิดขึ้นจริง
 *      เมื่อผู้ดูแลกรอกความสัมพันธ์ผิดทางเพียงเส้นเดียว · ผลคือ API ค้าง
 *      ไม่ใช่ตอบผิด และไม่มี error ให้เห็น
 *   2. **เพดานความลึกที่ตัดเงียบ ๆ อ่านเหมือน "ไม่มีอะไรพังต่อ"** ซึ่งกลับ
 *      ความหมายของคำตอบ · ต้องบอกว่าตัดไปกี่ตัว
 *   3. **ทิศทางกลับหัวได้ง่ายมาก** — "อะไรพึ่งฉัน" กับ "ฉันพึ่งอะไร"
 *      เป็นคนละคำถาม · ตอบผิดทิศแปลว่าประกาศดับผิดกลุ่มคน
 *   4. **ระยะห่างต้องเป็นระยะสั้นที่สุด** — ตัวที่ถึงได้สองทาง ต้องรายงาน
 *      ทางที่สั้นกว่า ไม่ใช่ทางที่บังเอิญเจอก่อน
 *   5. **ตัวเริ่มต้นไม่ใช่ผู้ได้รับผลกระทบของตัวเอง**
 */
import { describe, expect, it } from 'vitest';

import {
  MAX_DEPTH,
  impactOf,
  type CiEdge,
} from './impact-graph';

/** `a` พึ่งพา `b` — `b` ล่มแล้ว `a` พัง */
const dep = (a: string, b: string): CiEdge => ({ dependentId: a, dependsOnId: b });

describe('A · ทิศทาง', () => {
  /*
    เว็บ → แอป → ฐานข้อมูล · ฐานข้อมูลล่มแล้วพังทั้งสาย
    ส่วนเว็บล่มไม่มีใครพังตาม เพราะไม่มีใครพึ่งเว็บ
  */
  const edges = [dep('เว็บ', 'แอป'), dep('แอป', 'ฐานข้อมูล')];

  it('**"อะไรพังตามถ้าตัวนี้ล่ม" ไล่ขึ้นหาคนที่พึ่งพา**', () => {
    const r = impactOf('ฐานข้อมูล', edges);
    expect(r.affected.map((a) => a.id)).toEqual(['แอป', 'เว็บ']);
    expect(r.affected.map((a) => a.distance)).toEqual([1, 2]);
  });

  it('**ตัวที่ไม่มีใครพึ่ง ล่มแล้วไม่มีอะไรพังตาม**', () => {
    // ถ้าไล่ผิดทิศ ข้อนี้จะคืน "แอป, ฐานข้อมูล" ซึ่งกลับความหมายทั้งหมด
    expect(impactOf('เว็บ', edges).affected).toEqual([]);
  });

  it('ตัวกลางล่ม กระทบเฉพาะที่อยู่เหนือมัน', () => {
    expect(impactOf('แอป', edges).affected.map((a) => a.id)).toEqual(['เว็บ']);
  });

  it('**ตัวเริ่มต้นไม่นับเป็นผู้ได้รับผลกระทบของตัวเอง**', () => {
    expect(impactOf('ฐานข้อมูล', edges).affected.map((a) => a.id)).not.toContain('ฐานข้อมูล');
  });
});

describe('B · วงจร', () => {
  it('**วงจรต้องไม่ทำให้ไล่ไม่จบ**', () => {
    /*
      A พึ่ง B · B พึ่ง C · C พึ่ง A — เกิดขึ้นจริงเมื่อผู้ดูแลกรอกผิดทาง
      เส้นเดียว · ถ้าไม่กันไว้ API จะค้าง ไม่ใช่ตอบผิด และไม่มี error ให้เห็น
    */
    const edges = [dep('A', 'B'), dep('B', 'C'), dep('C', 'A')];
    const r = impactOf('A', edges);
    expect(r.affected.map((a) => a.id).sort()).toEqual(['B', 'C']);
    expect(r.hasCycle).toBe(true);
  });

  it('วงจรตรงตัว (สองตัวพึ่งกันเอง) ก็ต้องจบ', () => {
    const r = impactOf('X', [dep('X', 'Y'), dep('Y', 'X')]);
    expect(r.affected.map((a) => a.id)).toEqual(['Y']);
    expect(r.hasCycle).toBe(true);
  });

  it('**กราฟที่ไม่มีวงจรต้องไม่ถูกกล่าวหาว่ามีวงจร**', () => {
    /*
      ตัวที่ถึงได้สองทาง (เพชร) ไม่ใช่วงจร · ถ้ารายงานว่ามีวงจรทุกครั้งที่
      เจอตัวซ้ำ ธงนี้จะขึ้นตลอดเวลาแล้วไม่มีใครเชื่อมันอีก
    */
    const edges = [dep('บน', 'ซ้าย'), dep('บน', 'ขวา'), dep('ซ้าย', 'ล่าง'), dep('ขวา', 'ล่าง')];
    const r = impactOf('ล่าง', edges);
    expect(r.hasCycle).toBe(false);
    expect(r.affected.map((a) => a.id).sort()).toEqual(['ขวา', 'ซ้าย', 'บน']);
  });
});

describe('C · ระยะห่าง', () => {
  it('**ตัวที่ถึงได้สองทาง รายงานระยะที่สั้นกว่า**', () => {
    /*
      ระยะห่างบอกว่า "ห่างจากต้นเหตุกี่ชั้น" ซึ่งคนใช้เรียงลำดับว่าจะแจ้งใครก่อน ·
      การรายงานทางที่ยาวกว่าทำให้ระบบที่พังทันทีถูกจัดว่าอยู่ไกล
    */
    const edges = [dep('ปลาย', 'ต้น'), dep('กลาง', 'ต้น'), dep('ปลาย', 'กลาง')];
    const r = impactOf('ต้น', edges);
    const byId = new Map(r.affected.map((a) => [a.id, a.distance]));
    expect(byId.get('กลาง')).toBe(1);
    expect(byId.get('ปลาย')).toBe(1);
  });

  it('เรียงจากใกล้ไปไกล แล้วตามชื่อเมื่อระยะเท่ากัน', () => {
    // ลำดับต้องคงที่ระหว่างการเรียกสองครั้ง มิฉะนั้นหน้าจอจะสลับไปมา
    const edges = [dep('ข', 'ต้น'), dep('ก', 'ต้น'), dep('ค', 'ก')];
    expect(impactOf('ต้น', edges).affected.map((a) => `${a.id}:${String(a.distance)}`)).toEqual([
      'ก:1',
      'ข:1',
      'ค:2',
    ]);
  });
});

describe('D · เพดานความลึก', () => {
  /** สายยาว: n0 ← n1 ← n2 ← … (n1 พึ่ง n0) */
  function chain(length: number): CiEdge[] {
    const out: CiEdge[] = [];
    for (let i = 1; i <= length; i += 1) out.push(dep(`n${String(i)}`, `n${String(i - 1)}`));
    return out;
  }

  it('สายที่สั้นกว่าเพดาน ไล่ครบและไม่ตัดอะไร', () => {
    const r = impactOf('n0', chain(MAX_DEPTH - 1));
    expect(r.affected).toHaveLength(MAX_DEPTH - 1);
    expect(r.truncated).toBe(0);
  });

  it('**เพดานที่ตัดเงียบ ๆ อ่านเหมือน "ไม่มีอะไรพังต่อ" — ต้องบอกว่าตัดไปกี่ตัว**', () => {
    const r = impactOf('n0', chain(MAX_DEPTH + 3));
    expect(r.affected).toHaveLength(MAX_DEPTH);
    expect(r.truncated).toBe(3);
    expect(r.affected.at(-1)?.distance).toBe(MAX_DEPTH);
  });

  it('ไม่มีอะไรถูกตัด = ศูนย์ ไม่ใช่ `null`', () => {
    expect(impactOf('n0', chain(2)).truncated).toBe(0);
  });
});

describe('E · ขอบที่ใช้ไม่ได้', () => {
  it('**เส้นที่ชี้หาตัวเองคือวงจรที่สั้นที่สุด ต้องติดธง ไม่ใช่ข้ามเงียบ ๆ**', () => {
    /*
      ผู้ดูแลที่กรอก "เครื่อง A พึ่งพาเครื่อง A" กรอกผิด · การข้ามไปเฉย ๆ
      ทำให้เขาเห็นผลลัพธ์ที่ดูปกติแล้วไม่มีวันรู้

      เคสนี้ยังเป็นตัวแยกด้วยว่าการข้ามเส้นนั้นทำงานจริง — ด่านวงจรกับด่าน
      กันไล่ซ้ำบังผลของมันไว้ทั้งสองทาง ถ้าดูแค่ `affected` จะแยกไม่ออก
    */
    const r = impactOf('A', [dep('A', 'A'), dep('B', 'A')]);
    expect(r.affected.map((x) => x.id)).toEqual(['B']);
    expect(r.hasCycle).toBe(true);
  });

  it('**เส้นชี้หาตัวเองของตัวที่ไม่ใช่ต้นเหตุ ก็ต้องติดธง**', () => {
    // ด่านกันไล่ซ้ำจะบังไว้ถ้าตรวจตอนไล่ · ต้องตรวจตอนสร้างดัชนีจึงครอบทุกตัว
    const r = impactOf('A', [dep('B', 'A'), dep('B', 'B')]);
    expect(r.affected.map((x) => x.id)).toEqual(['B']);
    expect(r.hasCycle).toBe(true);
  });

  it('ตัวที่ไม่มีอยู่ในกราฟเลย = ไม่มีผลกระทบ ไม่ใช่ error', () => {
    expect(impactOf('ไม่มีจริง', [dep('A', 'B')]).affected).toEqual([]);
  });

  it('กราฟว่าง = ไม่มีผลกระทบ', () => {
    expect(impactOf('A', []).affected).toEqual([]);
  });
});
