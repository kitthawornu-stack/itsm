describe('สถิติเวลาตอบสนอง · B · สรุปผล', () => {
  /**
   * **หัวใจของทั้งไฟล์**
   *
   * 500 ที่ตอบกลับใน 2 มิลลิวินาที จะดึง p95 ลงจนระบบดูเร็วขึ้น
   * ตอนที่มันกำลังพัง
   */
  it('**คำขอที่ล้ม ไม่ถูกนับรวมในเวลา แต่ถูกนับจำนวน**', () => {
    const s = summarize([ok(100), ok(100), fail(1), fail(1)]);
    expect(s.p50).toBe(100);
    expect(s.failed).toBe(2);
    expect(s.total).toBe(4);
    expect(s.ok).toBe(2);
  });

  it('**บอกอัตราความล้มเหลวเป็นตัวเลข ไม่ใช่ให้คนไปหารเอง**', () => {
    const s = summarize([ok(10), ok(10), ok(10), fail(10)]);
    expect(s.failureRate).toBeCloseTo(0.25, 5);
  });

  /**
   * p95 จากตัวอย่างสามตัวคือตัวเลขที่อ่านเหมือนข้อเท็จจริงแต่ไม่มีอะไรรองรับ ·
   * ผู้เรียกต้องเห็นจำนวนเสมอ จึงจะตัดสินได้ว่าเชื่อได้แค่ไหน
   */
  it('**รายงานจำนวนตัวอย่างเสมอ**', () => {
    expect(summarize([ok(1), ok(2), ok(3)]).ok).toBe(3);
  });

  it('ทุกคำขอล้มหมด — เวลาเป็น `null` ไม่ใช่ศูนย์', () => {
    const s = summarize([fail(5), fail(6)]);
    expect(s.p50).toBeNull();
    expect(s.p95).toBeNull();
    expect(s.max).toBeNull();
    expect(s.failureRate).toBe(1);
  });

  it('ไม่มีคำขอเลย — ทุกอย่างเป็น `null` และอัตราล้มเหลวเป็น 0', () => {
    const s = summarize([]);
    expect(s.total).toBe(0);
    expect(s.p50).toBeNull();
    expect(s.failureRate).toBe(0);
  });

  it('รายงานค่าต่ำสุดและสูงสุดของที่สำเร็จ', () => {
    const s = summarize([ok(5), ok(50), ok(500), fail(9999)]);
    expect(s.min).toBe(5);
    expect(s.max).toBe(500);
  });

  it('ไม่แก้ข้อมูลที่รับเข้ามา', () => {
    const xs = [ok(30), ok(10)];
    const snapshot = JSON.stringify(xs);
    summarize(xs);
    expect(JSON.stringify(xs)).toBe(snapshot);
  });
});
