/**
 * ตัวเลขในแผนหลักต้องตรงกับเอกสารสถานะ
 *
 * `master-plan.html` เพิ่งได้บล็อก "สถานะจริง" ที่อ้างตัวเลขนับได้ ·
 * **ตัวเลขที่ไม่มีอะไรตรวจ จะเพี้ยนเงียบ ๆ** — เกิดขึ้นมาแล้วกับ
 * `jira-parity-checklist.md` ซึ่ง `web 34` ค้างอยู่หลายรอบทั้งที่มี 28 เคส
 * และไม่มีอะไรจับได้ จนกระทั่งมีตัวสแกนที่อ่านซอร์สจริง
 *
 * **เทียบกับเอกสารสถานะ ไม่ใช่กับตัวมันเอง** · เอกสารสถานะถูกเทียบกับซอร์ส
 * จริงโดย `status-doc.spec.ts` อยู่แล้ว · การผูกแผนไว้กับมัน ทำให้ตัวเลข
 * ในแผนตามซอร์สไปโดยปริยาย และเหลือที่ต้องดูแลด้วยมือเพียงที่เดียว
 *
 * ที่นี่ **ไม่ตรวจข้อความบรรยาย** — ประโยคอย่าง "ยังไม่มีข้อไหนเกิดขึ้นเลย"
 * พิสูจน์ด้วยเครื่องไม่ได้ · สิ่งที่ตรวจได้คือตัวเลข และความสอดคล้อง
 * ระหว่างสองเอกสารเท่านั้น
 */
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

import { describe, expect, it } from 'vitest';

const REPO = join(__dirname, '..', '..', '..');
const PLAN = readFileSync(join(REPO, 'docs', 'master-plan.html'), 'utf8');

/**
 * เฉพาะบล็อก "สถานะจริง" — ไม่ใช่ทั้งเอกสาร
 *
 * แผนพูดถึงตัวเลขหลายชุดในบริบทต่างกัน (วางแผนไว้ 28 กลุ่มงาน · ฝั่ง backend
 * วางแผนไว้ 16) · ถ้าค้นทั้งเอกสาร ตัวแกะจะเจอเลขแรกที่บังเอิญอยู่ใกล้คำนั้น
 * แล้วรายงานว่าไม่ตรงทั้งที่บล็อกสถานะถูกอยู่ — **รอบแรกเป็นแบบนั้นจริง**
 * และมันก็เปิดเผยว่าเอกสารมีเลขโมดูลสามชุดที่ขัดกันเองด้วย
 */
const STATUS_BLOCK = (() => {
  const at = PLAN.indexOf('สถานะจริง · ปรับปรุง');
  return at === -1 ? '' : PLAN.slice(at, at + 2500);
})();
const STATUS = readFileSync(join(REPO, 'docs', 'jira-parity-checklist.md'), 'utf8');

/** เลขที่เขียนไว้หน้าคำหนึ่ง เช่น "22 โมดูล" */
function numberBefore(doc: string, word: string): number | null {
  const m = new RegExp(`(\\d[\\d,]*)\\s*${word}`).exec(doc);
  return m === null ? null : Number((m[1] ?? '').replace(/,/g, ''));
}

describe('แผนหลัก · ตัวเลขต้องตรงกับเอกสารสถานะ', () => {
  /*
    **probe ทั้งสองทิศ** — ตัวแกะที่หาอะไรไม่เจอจะคืน `null` ทั้งคู่
    แล้วเคสข้างล่างจะเทียบ null กับ null ได้เท่ากันเสมอ
  */
  it('probe · แกะเลขจากทั้งสองเอกสารได้จริง', () => {
    expect(STATUS_BLOCK.length, 'หาบล็อกสถานะจริงไม่เจอ').toBeGreaterThan(500);
    expect(numberBefore(STATUS_BLOCK, 'โมดูล')).not.toBeNull();
    expect(numberBefore(STATUS, 'โมดูล')).not.toBeNull();
  });

  it('probe · คำที่ไม่มีในเอกสาร ได้ null ไม่ใช่เลขมั่ว', () => {
    expect(numberBefore(STATUS_BLOCK, 'คำที่ไม่มีทางอยู่ในเอกสารนี้')).toBeNull();
  });

  /**
   * **ตัวเลขทุกตัวในแผนต้องตรงกับเอกสารสถานะ**
   *
   * เอกสารสถานะถูกเทียบกับซอร์สจริงอยู่แล้ว · ผูกแผนไว้กับมันแล้วตัวเลข
   * ในแผนจะตามซอร์สไปเอง
   */
  it('**โมดูล · หน้าจอ · endpoint · เทสต์ · ไฟล์เทสต์ ตรงกันทั้งสองเอกสาร**', () => {
    for (const word of ['โมดูล', 'หน้าจอ', 'endpoint', 'เทสต์', 'ไฟล์เทสต์']) {
      const inPlan = numberBefore(STATUS_BLOCK, word);
      const inStatus = numberBefore(STATUS, word);
      expect(inPlan, `แผนไม่ได้บอกจำนวน "${word}"`).not.toBeNull();
      expect(inPlan, `แผนบอก "${word}" ไม่ตรงกับเอกสารสถานะ`).toBe(inStatus);
    }
  });

  /**
   * **แผนต้องไม่สัญญาสิ่งที่ ADR ตัดออกไปแล้ว**
   *
   * ADR-003 ตัดสินว่าองค์กรไม่ได้ใช้ AD/LDAP จึงไม่ทำ SAML · OIDC · SCIM ·
   * แผนฉบับแรกเขียนไว้ก่อนได้คำตอบนั้น · **แผนที่ยังสัญญาสิ่งที่ตัดไปแล้ว
   * อันตรายกว่าแผนที่ไม่มีรายละเอียด** เพราะมีคนวางแผนงานต่อจากมัน
   *
   * ตรวจว่าทุกที่ที่เอ่ยถึงมัน มีคำว่า ADR-003 กำกับอยู่ใกล้ ๆ —
   * ไม่ได้ห้ามพูดถึง แต่ห้ามพูดถึงโดยไม่บอกว่าถูกตัดแล้ว
   */
  it('**ทุกที่ที่พูดถึง SAML/LDAP/SCIM ต้องอ้าง ADR-003 กำกับ**', () => {
    const orphans: string[] = [];
    for (const m of PLAN.matchAll(/SAML|LDAP|SCIM/g)) {
      const around = PLAN.slice(Math.max(0, m.index - 400), m.index + 400);
      if (!around.includes('ADR-003')) orphans.push(around.slice(350, 460));
    }
    expect(orphans, ['ที่ที่พูดถึง SSO/LDAP โดยไม่บอกว่าตัดแล้ว:', ...orphans].join('\n')).toEqual(
      [],
    );
  });

  /**
   * แผนต้องบอกวันที่ปรับปรุง · เอกสารสถานะที่ไม่มีวันที่ ทำให้คนอ่านไม่รู้ว่า
   * กำลังอ่านของเมื่อไร แล้วเชื่อว่าเป็นปัจจุบันเสมอ
   */
  it('บล็อกสถานะจริงมีวันที่กำกับ', () => {
    expect(PLAN).toMatch(/สถานะจริง · ปรับปรุง \d{1,2} [ก-๙.]+ \d{4}/);
  });
});
