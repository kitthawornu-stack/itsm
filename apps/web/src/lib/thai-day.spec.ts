/**
 * ขอบเขตของวันตามเวลาไทย — เทสต์เป็นข้อกำหนด
 *
 * เซิร์ฟเวอร์เดินด้วย UTC · `toISOString().slice(0, 10)` ตรง ๆ ทำให้
 * **ช่วง 00:00–07:00 ตามเวลาไทยถูกนับเป็นวันก่อนหน้า** ซึ่งเป็นช่วงที่งาน
 * เปลี่ยนแปลงส่วนใหญ่ถูกนัดไว้พอดี (นอกเวลาทำการ) · ปฏิทินจะแสดงงาน
 * คืนวันเสาร์ไปอยู่วันศุกร์ทั้งหมดโดยไม่มีอะไรฟ้อง
 */
import { describe, expect, it } from 'vitest';

import { daysCovered, shiftDay, thaiClock, thaiDayKey, thaiDayLabel, thaiMidnight } from './thai-day';

describe('A · คีย์ของวัน', () => {
  it('**ตีสองตามเวลาไทยคือวันนั้น ไม่ใช่วันก่อนหน้า**', () => {
    // 2026-01-10T19:00Z = 2026-01-11 ตีสอง ตามเวลาไทย
    expect(thaiDayKey(new Date('2026-01-10T19:00:00.000Z'))).toBe('2026-01-11');
  });

  it('ห้าโมงเย็นตามเวลาไทย ยังเป็นวันเดียวกัน', () => {
    // 2026-01-10T10:00Z = 17:00 ตามเวลาไทย
    expect(thaiDayKey(new Date('2026-01-10T10:00:00.000Z'))).toBe('2026-01-10');
  });

  it('**เที่ยงคืนตรงตามเวลาไทย คือวันใหม่**', () => {
    // เขตแดนที่ `<` กับ `<=` ให้คำตอบต่างกัน
    expect(thaiDayKey(new Date('2026-01-10T17:00:00.000Z'))).toBe('2026-01-11');
    expect(thaiDayKey(new Date('2026-01-10T16:59:59.999Z'))).toBe('2026-01-10');
  });

  it('เที่ยงคืนไทยแปลงกลับเป็น UTC ได้ตรง', () => {
    expect(thaiMidnight('2026-01-11').toISOString()).toBe('2026-01-10T17:00:00.000Z');
  });

  it('เลื่อนวันข้ามเดือนและข้ามปีได้', () => {
    expect(shiftDay('2026-01-31', 1)).toBe('2026-02-01');
    expect(shiftDay('2026-01-01', -1)).toBe('2025-12-31');
    expect(shiftDay('2028-02-28', 1)).toBe('2028-02-29');
  });
});

describe('B · ป้ายกำกับ', () => {
  it('**ปีพุทธศักราช และชื่อวันอยู่หน้าสุด**', () => {
    /*
      ชื่อวันมาก่อนเพราะวันเสาร์–อาทิตย์คือสิ่งที่คนหาในปฏิทินการเปลี่ยนแปลง —
      งานส่วนใหญ่ถูกนัดไว้สุดสัปดาห์
    */
    expect(thaiDayLabel('2026-01-10')).toBe('เสาร์ 10 ม.ค. 2569');
    expect(thaiDayLabel('2026-12-31')).toBe('พฤหัสบดี 31 ธ.ค. 2569');
  });

  it('เวลาบนนาฬิกาไทย', () => {
    expect(thaiClock('2026-01-10T19:00:00.000Z')).toBe('02:00');
    expect(thaiClock('2026-01-10T17:00:00.000Z')).toBe('00:00');
  });
});

describe('C · วันที่ช่วงเวลาหนึ่งกินพื้นที่', () => {
  it('งานคืนเดียวอยู่วันเดียว', () => {
    // 02:00–05:00 ของวันที่ 11 ตามเวลาไทย
    expect(daysCovered('2026-01-10T19:00:00.000Z', '2026-01-10T22:00:00.000Z')).toEqual([
      '2026-01-11',
    ]);
  });

  it('**งานที่จบเที่ยงคืนพอดี ไม่กินวันถัดไป** — ช่วงเป็น `[start, end)`', () => {
    /*
      ถ้านับปลายปิดด้วย งานที่จบเที่ยงคืนจะโผล่สองวันในปฏิทิน แล้วคนจะนับ
      จำนวนงานผิดทุกครั้งที่มีงานลากยาวถึงเที่ยงคืน
    */
    expect(daysCovered('2026-01-10T19:00:00.000Z', '2026-01-10T17:00:00.000Z')).toEqual([]);
    expect(daysCovered('2026-01-10T14:00:00.000Z', '2026-01-10T17:00:00.000Z')).toEqual([
      '2026-01-10',
    ]);
  });

  it('งานที่ลากข้ามคืน อยู่ทั้งสองวัน', () => {
    // 21:00 วันที่ 10 → 03:00 วันที่ 11 ตามเวลาไทย
    expect(daysCovered('2026-01-10T14:00:00.000Z', '2026-01-10T20:00:00.000Z')).toEqual([
      '2026-01-10',
      '2026-01-11',
    ]);
  });

  it('ช่วงห้ามยาวหลายวัน คืนครบทุกวัน', () => {
    const days = daysCovered('2026-04-12T17:00:00.000Z', '2026-04-16T17:00:00.000Z');
    expect(days).toEqual(['2026-04-13', '2026-04-14', '2026-04-15', '2026-04-16']);
  });
});
