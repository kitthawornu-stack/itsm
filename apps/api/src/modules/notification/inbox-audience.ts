/**
 * "กล่องแจ้งเตือนนี้เป็นของใคร"
 *
 * เดิมเงื่อนไขคือ `OR: [{ userId: ฉัน }, { userId: null }]` พร้อมคอมเมนต์ว่า
 * `userId` เป็น null คือ "การแจ้งเตือนระดับทีม" · **แต่ไม่มีอะไรนิยามว่าทีมคือใคร**
 * ผลจริงคือแถวนั้นไปถึงทุกคนในองค์กร รวมคนที่ไม่มีสิทธิ์เห็นโปรเจกต์นั้นเลย
 *
 * ทีมของงานหนึ่ง = คนที่เข้าถึงโปรเจกต์ของงานนั้นได้ · นิยามนี้อยู่ที่เดียว
 * และถูกใช้ทั้งตอนอ่านรายการ ตอนนับที่ยังไม่อ่าน และตอนกดอ่านแล้ว
 *
 * ฟังก์ชันบริสุทธิ์ · ไม่แตะฐานข้อมูล ไม่อ่านนาฬิกา
 */

/** เงื่อนไขที่ส่งต่อให้ Prisma ได้ตรง ๆ — แคบพอที่ TypeScript ตรวจรูปให้ */
export interface InboxAudience {
  OR: Array<{ userId: bigint | null; workItem?: { projectId: { in: bigint[] } } }>;
}

/**
 * @param actorId ผู้ใช้ที่ล็อกอินอยู่ · `null` = ไม่มีกล่อง ไม่ใช่เห็นทุกอย่าง
 * @param browsableProjectIds โปรเจกต์ที่คนนี้เข้าถึงได้จริง (ถามจากโมดูล permission)
 */
export function inboxAudience(
  actorId: bigint | null,
  browsableProjectIds: readonly bigint[],
): InboxAudience {
  if (actorId === null) {
    /*
      **`OR: []` ใน Prisma แปลว่าไม่ตรงสักแถว** ไม่ใช่ไม่กรอง — ตรงกับที่ต้องการ
      คือปิดสนิท · session guard กันไว้ก่อนถึงตรงนี้อยู่แล้ว แต่ค่าปริยาย
      ของฟังก์ชันนี้ต้องเป็นการปฏิเสธ ไม่ใช่การอนุญาต
    */
    return { OR: [] };
  }

  const mine = { userId: actorId };
  /*
    ไม่มีโปรเจกต์ที่เห็นได้เลย → ไม่มีแถวระดับทีมสักแถว · **ไม่ใช่** ใส่
    `{ userId: null }` เปล่า ๆ ซึ่งจะกลายเป็น "เห็นทุกแถว" ในวันที่รายการว่าง
    — ข้อมูลที่ไม่ครบต้องแปลว่าไม่มีสิทธิ์ (§9)
  */
  if (browsableProjectIds.length === 0) return { OR: [mine] };

  /*
    แถวระดับทีม **ต้องผูกกับงาน** · แถวที่ `workItemId` เป็น null ตอบไม่ได้ว่า
    เป็นของโปรเจกต์ไหน จึงตอบไม่ได้ว่าใครควรเห็น · เงื่อนไขความสัมพันธ์นี้
    ตัดมันทิ้งเองอยู่แล้ว เพราะ null ไม่มีแถวปลายทางให้ตรวจ
  */
  return {
    OR: [mine, { userId: null, workItem: { projectId: { in: [...browsableProjectIds] } } }],
  };
}
