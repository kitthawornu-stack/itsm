/**
 * ข้อกำหนดของตารางเวลาส่งรายงาน — **เขียนก่อนโค้ด**
 *
 * ## ทำไมต้องเป็นเอนจินแยก
 *
 * "ครั้งต่อไปเมื่อไร" เป็นคำถามที่ผิดแล้ว **ไม่มีใครเห็น** — รายงานที่ไม่ถูกส่ง
 * ไม่มีใครทวง เพราะไม่มีใครรู้ว่าควรได้รับ · และรายงานที่ส่งผิดเวลาก็ยัง
 * อ่านได้ตามปกติ · ความผิดทั้งสองแบบจึงเงียบสนิท
 *
 * ## สิ่งที่ผิดแล้วเงียบ
 *
 *   1. **คิดเป็น UTC แทนที่จะเป็นเวลาไทย** — "ทุกวัน 08:00" ที่คิดเป็น UTC
 *      จะส่งตอน 15:00 ตามเวลาไทย · ไม่มี error ไม่มีอะไรบอก มีแต่คนสงสัยว่า
 *      ทำไมรายงานเช้ามาตอนบ่าย
 *   2. **รายเดือนวันที่ 31 ในเดือนที่ไม่มีวันที่ 31** — ถ้าปล่อยให้ล้นไป
 *      วันที่ 1 ของเดือนถัดไป รายงานเดือนกุมภาพันธ์จะมาถึงตอนต้นเดือนมีนาคม
 *      และถ้าข้ามไปเลย เดือนนั้นจะไม่มีรายงานโดยไม่มีใครรู้
 *   3. **ยิงซ้ำรอบเดิม** — ครั้งต่อไปต้อง **หลัง** ครั้งล่าสุดเสมอ
 *      มิฉะนั้นตัวตั้งเวลาที่รันทุกนาทีจะส่งซ้ำทั้งวัน
 *   4. **ตามเก็บรอบที่ตกไปทั้งหมด** — เครื่องดับสามวันแล้วกลับมา
 *      ไม่ควรส่งรายงานย้อนหลังสามฉบับพร้อมกัน · แต่ต้อง **บอกได้ว่าตกไปกี่รอบ**
 *      ไม่ใช่เงียบ ๆ เหมือนไม่เคยมีอะไรเกิดขึ้น
 */
import { describe, expect, it } from 'vitest';
import { toUtcDate } from '@itsm/types';

import { nextRunAt, missedRuns, type Schedule } from './schedule';

/** เวลาไทยเป็น UTC — 08:00 ไทย = 01:00 UTC */
const thai = (s: string): ReturnType<typeof toUtcDate> =>
  toUtcDate(Date.parse(`${s}+07:00`));

const daily8: Schedule = { kind: 'daily', hour: 8, minute: 0 };
/** จันทร์ = 1 · ตรงกับ `Date.getUTCDay()` ที่ 0 = อาทิตย์ */
const weeklyMon9: Schedule = { kind: 'weekly', weekday: 1, hour: 9, minute: 30 };
const monthly31: Schedule = { kind: 'monthly', day: 31, hour: 7, minute: 0 };

describe('ตารางเวลาส่งรายงาน', () => {
  describe('A · รายวัน', () => {
    /**
     * **หัวใจของไฟล์นี้**
     *
     * "ทุกวัน 08:00" หมายถึงแปดโมงเช้าตามเวลาไทย · ถ้าคิดเป็น UTC
     * รายงานจะมาถึงตอนบ่ายสามโดยไม่มีอะไรบอกว่าผิด
     */
    it('**08:00 หมายถึงเวลาไทย ไม่ใช่ UTC**', () => {
      const next = nextRunAt(daily8, thai('2026-09-03T06:00:00'), null);
      expect(next.toISOString()).toBe('2026-09-03T01:00:00.000Z');
    });

    it('เลยเวลาของวันนี้แล้ว = ไปวันพรุ่งนี้', () => {
      const next = nextRunAt(daily8, thai('2026-09-03T09:00:00'), null);
      expect(next.toISOString()).toBe('2026-09-04T01:00:00.000Z');
    });

    it('ตรงเวลาพอดี = รอบนี้เลย ไม่ใช่ข้ามไปพรุ่งนี้', () => {
      const next = nextRunAt(daily8, thai('2026-09-03T08:00:00'), null);
      expect(next.toISOString()).toBe('2026-09-03T01:00:00.000Z');
    });

    /**
     * **ครั้งต่อไปต้องหลังครั้งล่าสุดเสมอ**
     *
     * ตัวตั้งเวลารันทุกนาที · ถ้าครั้งต่อไปยังเป็นเวลาเดิมหลังส่งไปแล้ว
     * มันจะส่งซ้ำทุกนาทีจนหมดวัน
     */
    it('**ส่งไปแล้วรอบนี้ = ไปรอบถัดไป ไม่ใช่รอบเดิม**', () => {
      const at = thai('2026-09-03T08:00:00');
      const next = nextRunAt(daily8, at, at);
      expect(next.toISOString()).toBe('2026-09-04T01:00:00.000Z');
    });
  });

  describe('B · รายสัปดาห์', () => {
    it('วันจันทร์ 09:30 เวลาไทย', () => {
      // 2026-09-03 เป็นวันพฤหัสบดี → จันทร์ถัดไปคือ 2026-09-07
      const next = nextRunAt(weeklyMon9, thai('2026-09-03T12:00:00'), null);
      expect(next.toISOString()).toBe('2026-09-07T02:30:00.000Z');
    });

    it('วันนี้เป็นวันนั้นและยังไม่ถึงเวลา = วันนี้', () => {
      const next = nextRunAt(weeklyMon9, thai('2026-09-07T08:00:00'), null);
      expect(next.toISOString()).toBe('2026-09-07T02:30:00.000Z');
    });

    it('วันนี้เป็นวันนั้นแต่เลยเวลาแล้ว = สัปดาห์หน้า', () => {
      const next = nextRunAt(weeklyMon9, thai('2026-09-07T10:00:00'), null);
      expect(next.toISOString()).toBe('2026-09-14T02:30:00.000Z');
    });
  });

  describe('C · รายเดือน', () => {
    it('วันที่ที่มีอยู่จริง ใช้วันนั้น', () => {
      const next = nextRunAt(
        { kind: 'monthly', day: 5, hour: 7, minute: 0 },
        thai('2026-09-01T00:00:00'),
        null,
      );
      expect(next.toISOString()).toBe('2026-09-05T00:00:00.000Z');
    });

    /**
     * **วันที่ 31 ในเดือนที่ไม่มีวันที่ 31 = วันสุดท้ายของเดือนนั้น**
     *
     * ล้นไปวันที่ 1 ของเดือนถัดไป ทำให้รายงานเดือนกุมภาพันธ์มาถึงต้นเดือน
     * มีนาคม · ข้ามไปเลยทำให้เดือนนั้นไม่มีรายงานโดยไม่มีใครรู้ ·
     * ทั้งสองอย่างเงียบเท่ากัน
     */
    it('**วันที่ 31 ในเดือนที่มี 30 วัน = วันที่ 30**', () => {
      const next = nextRunAt(monthly31, thai('2026-09-01T00:00:00'), null);
      expect(next.toISOString()).toBe('2026-09-30T00:00:00.000Z');
    });

    it('**วันที่ 31 ในเดือนกุมภาพันธ์ = วันสุดท้ายของเดือน**', () => {
      const next = nextRunAt(monthly31, thai('2026-02-01T00:00:00'), null);
      expect(next.toISOString()).toBe('2026-02-28T00:00:00.000Z');
    });

    it('เลยวันของเดือนนี้แล้ว = เดือนหน้า', () => {
      const next = nextRunAt(
        { kind: 'monthly', day: 5, hour: 7, minute: 0 },
        thai('2026-09-10T00:00:00'),
        null,
      );
      expect(next.toISOString()).toBe('2026-10-05T00:00:00.000Z');
    });

    it('ข้ามปีได้', () => {
      const next = nextRunAt(
        { kind: 'monthly', day: 5, hour: 7, minute: 0 },
        thai('2026-12-10T00:00:00'),
        null,
      );
      expect(next.toISOString()).toBe('2027-01-05T00:00:00.000Z');
    });
  });

  describe('D · รอบที่ตกไป', () => {
    /**
     * **ไม่ส่งย้อนหลังทั้งกอง แต่ต้องบอกได้ว่าตกไปกี่รอบ**
     *
     * เครื่องดับสามวันแล้วกลับมา ไม่ควรส่งรายงานสามฉบับพร้อมกัน —
     * ผู้รับจะเห็นเป็นสแปมแล้วเลิกอ่านทั้งหมด · แต่ถ้าเงียบไปเลย
     * ก็ไม่มีใครรู้ว่าเคยมีรอบที่ไม่ได้ส่ง
     */
    it('**นับรอบที่ตกไปได้ ไม่ใช่แค่รู้ว่าตก**', () => {
      const last = thai('2026-09-01T08:00:00');
      const now = thai('2026-09-04T09:00:00');
      expect(missedRuns(daily8, last, now)).toBe(3);
    });

    it('ยังไม่ถึงรอบถัดไป = ไม่มีรอบที่ตก', () => {
      const last = thai('2026-09-03T08:00:00');
      const now = thai('2026-09-03T20:00:00');
      expect(missedRuns(daily8, last, now)).toBe(0);
    });

    it('ถึงรอบพอดี = ตกไป 1 รอบ ซึ่งคือรอบที่กำลังจะส่ง', () => {
      const last = thai('2026-09-03T08:00:00');
      const now = thai('2026-09-04T08:00:00');
      expect(missedRuns(daily8, last, now)).toBe(1);
    });

    /**
     * ยังไม่เคยส่งเลย = ยังไม่ถือว่าตก · ตารางที่เพิ่งสร้างไม่ควรรายงานว่า
     * พลาดไปแล้วตั้งแต่ยังไม่เริ่ม
     */
    it('ยังไม่เคยส่ง = ไม่นับว่าตก', () => {
      expect(missedRuns(daily8, null, thai('2026-09-04T09:00:00'))).toBe(0);
    });

    /**
     * **เพดานการนับ** — เครื่องที่ดับไปหนึ่งปีไม่ควรวนนับ 365 รอบ
     * ทุกครั้งที่ตัวตั้งเวลาตื่น · ตัวเลขที่เกินเพดานยังบอกได้ว่า "อย่างน้อย"
     */
    it('นับได้ไม่เกินเพดาน และไม่วนค้าง', () => {
      const last = thai('2020-01-01T08:00:00');
      const now = thai('2026-09-04T09:00:00');
      const n = missedRuns(daily8, last, now);
      expect(n).toBeGreaterThan(0);
      expect(n).toBeLessThanOrEqual(400);
    });
  });
});
