/**
 * ข้อกำหนดของเพดานงานที่ทำพร้อมกัน (WIP Limit) — **เขียนก่อนโค้ด**
 *
 * ## เพดานนี้มีไว้ทำอะไร
 *
 * บอกทีมว่าคอลัมน์หนึ่งมีงานค้างเกินที่ตกลงกันไว้ · จุดประสงค์คือให้ปิดของเดิม
 * ก่อนหยิบของใหม่ ไม่ใช่ห้ามไม่ให้ทำงาน
 *
 * ## สิ่งที่ผิดแล้วเงียบ
 *
 *   1. **นับจากจำนวนการ์ดที่แสดง ไม่ใช่จำนวนจริง** — กระดานดึงการ์ดมาคอลัมน์ละ
 *      ไม่เกิน 100 ใบ · คอลัมน์ที่มีงานจริง 150 ใบจะรายงานว่า 100
 *      แล้วเพดาน 120 จะดูเหมือนยังไม่เต็ม **ทั้งที่เกินไปแล้ว 30 ใบ**
 *      · เอนจินนี้จึงรับ "จำนวน" เป็นตัวเลขที่ผู้เรียกต้องนับมาเอง
 *      และไม่รับรายการการ์ดเลย เพื่อไม่ให้มีทางนับผิดแบบนั้นได้
 *   2. **เพดาน 0 ถูกอ่านเป็น "ไม่มีเพดาน"** — `if (!max)` ใน JavaScript
 *      ให้ผลเดียวกันกับ `undefined` · ทั้งสองอย่างต้องแยกกันให้ขาด
 *   3. **"เต็มพอดี" ถูกรายงานว่า "เกิน"** — คนที่เห็นคำเตือนทั้งที่ยังไม่ผิด
 *      จะเลิกอ่านคำเตือน แล้ววันที่เกินจริงก็ไม่มีใครสนใจ
 *   4. **หลายสถานะที่ยุบเป็นคอลัมน์เดียว ตั้งเพดานไม่ตรงกัน** — กระดานยุบ
 *      สถานะชื่อซ้ำจากหลาย workflow ให้เป็นคอลัมน์เดียว · ถ้าเลือกมาแสดง
 *      อันเดียวเงียบ ๆ ครึ่งหนึ่งของทีมจะอ่านเพดานที่ไม่ได้ใช้จริง
 */
import { describe, expect, it } from 'vitest';

import { evaluateWip, isValidWipLimit, wipLimitOf, WIP_LIMIT_MAX } from './wip-limit';

describe('เพดานงานที่ทำพร้อมกัน', () => {
  describe('ค่าที่ตั้งได้', () => {
    it('ต้องเป็นจำนวนเต็มบวก', () => {
      expect(isValidWipLimit(1)).toBe(true);
      expect(isValidWipLimit(25)).toBe(true);
      expect(isValidWipLimit(WIP_LIMIT_MAX)).toBe(true);
    });

    /**
     * **0 ไม่ใช่ "ไม่มีเพดาน" และไม่ใช่ค่าที่ตั้งได้**
     *
     * คอลัมน์ที่ห้ามมีงานเลยไม่ใช่เพดาน แต่คือคอลัมน์ที่ไม่ควรมีอยู่ ·
     * และที่สำคัญกว่า: `0` กับ "ไม่ได้ตั้ง" ให้ผลเหมือนกันใน `if (!max)`
     * ถ้ายอมให้เก็บ 0 ได้ วันหนึ่งจะมีคนเขียนเงื่อนไขแบบนั้นแล้วเพดาน
     * ที่เข้มที่สุดจะกลายเป็นไม่มีเพดาน
     */
    it('**0 ตั้งไม่ได้ — ไม่ใช่ "ไม่มีเพดาน"**', () => {
      expect(isValidWipLimit(0)).toBe(false);
    });

    it('ค่าติดลบ · เศษส่วน · ค่าที่ไม่ใช่ตัวเลข ตั้งไม่ได้', () => {
      expect(isValidWipLimit(-1)).toBe(false);
      expect(isValidWipLimit(2.5)).toBe(false);
      expect(isValidWipLimit(Number.NaN)).toBe(false);
      expect(isValidWipLimit(Number.POSITIVE_INFINITY)).toBe(false);
    });

    it('เกินเพดานสูงสุดตั้งไม่ได้ — เพดานที่ใหญ่กว่างานทั้งโปรเจกต์ไม่ได้เตือนอะไรใคร', () => {
      expect(isValidWipLimit(WIP_LIMIT_MAX + 1)).toBe(false);
    });
  });

  describe('เพดานของคอลัมน์ที่ยุบมาจากหลายสถานะ', () => {
    it('ไม่มีสถานะไหนตั้งเพดานไว้ = ไม่มีเพดาน', () => {
      expect(wipLimitOf(['1', '2'], new Map())).toEqual({ kind: 'none' });
    });

    it('สถานะเดียวที่ตั้งไว้ = ใช้ค่านั้น', () => {
      expect(wipLimitOf(['1', '2'], new Map([['2', 5]]))).toEqual({ kind: 'limit', max: 5 });
    });

    it('ทุกสถานะตั้งค่าเท่ากัน = ใช้ค่านั้น ไม่ใช่กำกวม', () => {
      expect(
        wipLimitOf(
          ['1', '2'],
          new Map([
            ['1', 5],
            ['2', 5],
          ]),
        ),
      ).toEqual({ kind: 'limit', max: 5 });
    });

    /**
     * **ตั้งไม่ตรงกัน = กำกวม ไม่ใช่เลือกมาอันหนึ่ง**
     *
     * กติกาเดียวกับขอบเขตของ Scrum ที่มีหลายรอบเปิดพร้อมกัน — การเลือก
     * มาแสดงอันเดียวเงียบ ๆ ทำให้คนอ่านเพดานที่ไม่ได้ใช้จริง
     */
    it('**ตั้งไม่ตรงกัน = กำกวม และบอกค่าที่เจอทั้งหมด**', () => {
      const got = wipLimitOf(
        ['1', '2', '3'],
        new Map([
          ['1', 5],
          ['3', 8],
        ]),
      );
      expect(got).toEqual({ kind: 'ambiguous', values: [5, 8] });
    });

    it('ค่าที่กำกวมเรียงจากน้อยไปมาก เพื่อให้ข้อความคงที่', () => {
      const got = wipLimitOf(
        ['1', '2'],
        new Map([
          ['1', 9],
          ['2', 3],
        ]),
      );
      expect(got).toEqual({ kind: 'ambiguous', values: [3, 9] });
    });
  });

  describe('การตัดสินว่าเกินหรือยัง', () => {
    it('ไม่มีเพดาน = ไม่ตัดสินอะไร', () => {
      expect(evaluateWip(999, { kind: 'none' })).toEqual({ kind: 'no-limit', count: 999 });
    });

    it('ต่ำกว่าเพดาน = บอกว่าเหลืออีกเท่าไร', () => {
      expect(evaluateWip(3, { kind: 'limit', max: 5 })).toEqual({
        kind: 'under',
        count: 3,
        max: 5,
        remaining: 2,
      });
    });

    /**
     * **"เต็มพอดี" ไม่ใช่ "เกิน"**
     *
     * เพดาน 5 ที่มีงาน 5 ใบคือสิ่งที่ตกลงกันไว้ ไม่ใช่การละเมิด ·
     * ถ้าเตือนตรงนี้ คนจะเห็นคำเตือนตลอดเวลาแล้วเลิกอ่าน
     */
    it('**เต็มพอดี = `at` ไม่ใช่ `over`**', () => {
      expect(evaluateWip(5, { kind: 'limit', max: 5 })).toEqual({ kind: 'at', count: 5, max: 5 });
    });

    it('เกิน = บอกว่าเกินไปกี่ใบ ไม่ใช่แค่ว่าเกิน', () => {
      expect(evaluateWip(8, { kind: 'limit', max: 5 })).toEqual({
        kind: 'over',
        count: 8,
        max: 5,
        excess: 3,
      });
    });

    /**
     * **เพดาน 0 ที่หลุดเข้ามาได้ ต้องไม่กลายเป็น "ไม่มีเพดาน"**
     *
     * `isValidWipLimit` กันไว้ที่ทางเข้าแล้ว แต่ข้อมูลเก่าหรือการแก้ฐานข้อมูล
     * ตรง ๆ ทำให้ 0 หลุดเข้ามาได้ · เคสนี้พิสูจน์ว่าเอนจินไม่ได้ใช้ `if (!max)`
     */
    it('**เพดาน 0 กับงาน 0 ใบ = เต็มพอดี ไม่ใช่ไม่มีเพดาน**', () => {
      expect(evaluateWip(0, { kind: 'limit', max: 0 })).toEqual({ kind: 'at', count: 0, max: 0 });
    });

    it('คอลัมน์ว่างที่มีเพดาน = ต่ำกว่าเพดาน ไม่ใช่ไม่มีเพดาน', () => {
      expect(evaluateWip(0, { kind: 'limit', max: 5 })).toEqual({
        kind: 'under',
        count: 0,
        max: 5,
        remaining: 5,
      });
    });

    it('กำกวม = ไม่ตัดสิน แต่ยังบอกจำนวนจริง', () => {
      expect(evaluateWip(7, { kind: 'ambiguous', values: [3, 9] })).toEqual({
        kind: 'ambiguous',
        count: 7,
        values: [3, 9],
      });
    });
  });

  /*
    **เอนจินไม่รับรายการการ์ด รับแต่จำนวน** — เป็นข้อกำหนดเชิงรูปร่าง
    ที่พิสูจน์ที่นี่ไม่ได้ · เคยเขียนเป็นเทสต์ที่ยัดอาร์เรย์เข้าไปแล้วยืนยันว่า
    ผลไม่สมเหตุสมผล ซึ่ง **ผ่านเสมอไม่ว่าโค้ดทำอะไร** จึงลบทิ้ง
    · ด่านจริงของข้อนี้คือตัวสแกนซอร์สที่ยืนยันว่า `boardOf` นับจำนวน
    ด้วยคิวรีของตัวเอง ไม่ใช่จาก `cards.length` ซึ่งถูกตัดที่ 100 ใบ
    — อยู่ที่ `board-wip-wiring.spec.ts`
  */
});
