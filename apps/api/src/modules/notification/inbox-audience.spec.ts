/**
 * ข้อกำหนดของ "กล่องแจ้งเตือนนี้เป็นของใคร" — **เขียนก่อนโค้ด**
 *
 * ## ทำไมต้องมีไฟล์นี้
 *
 * เดิมกล่องแจ้งเตือนอ่านด้วยเงื่อนไข `OR: [{ userId: ฉัน }, { userId: null }]`
 * โดยมีคอมเมนต์ว่า `userId` เป็น null คือ "การแจ้งเตือนระดับทีม" ·
 * **แต่ไม่มีอะไรนิยามว่าทีมคือใคร** ผลจริงคือแถวนั้นไปถึง *ทุกคนในองค์กร*
 *
 * เจอด้วย `authz-smoke.spec.ts`: ผู้ใช้ที่ไม่ได้อยู่กลุ่มไหนเลยและไม่มีสิทธิ์
 * เห็นโปรเจกต์ใดเลย เรียก `GET /api/v1/notifications` แล้วได้ **20 แถว**
 * ซึ่งเป็นคำเตือน SLA ที่มีคีย์งานและหัวข้อของงานจริงอยู่ในนั้น
 * (วัดในฐานข้อมูลพัฒนา: 21 แถวที่ `user_id IS NULL` ทั้งหมดเป็น `sla.threshold`)
 *
 * ## เหตุผลที่แยกเป็นฟังก์ชันบริสุทธิ์
 *
 * เงื่อนไขนี้ถูกใช้สามที่ (อ่านรายการ · นับที่ยังไม่อ่าน · กดอ่านแล้ว) ·
 * ถ้าเขียนซ้ำสามครั้ง การแก้ที่เดียวจะทิ้งอีกสองที่ไว้แบบเดิมโดยไม่มีใครเห็น
 */
import { describe, expect, it } from 'vitest';

import { inboxAudience } from './inbox-audience';

const ME = 7n;

describe('กล่องแจ้งเตือน · ขอบเขตผู้รับ', () => {
  it('การแจ้งเตือนที่จ่าหน้าถึงฉัน เป็นของฉันเสมอ', () => {
    const w = inboxAudience(ME, [1n, 2n]);
    expect(w.OR).toContainEqual({ userId: ME });
  });

  /**
   * **หัวใจของทั้งไฟล์**
   *
   * แถวระดับทีมต้องผูกกับงานในโปรเจกต์ที่คนอ่านเข้าถึงได้ ·
   * ไม่ใช่ "ทุกแถวที่ยังไม่ระบุตัวบุคคล"
   */
  it('**แถวระดับทีม จำกัดเฉพาะโปรเจกต์ที่คนอ่านเห็นได้**', () => {
    const w = inboxAudience(ME, [3n, 9n]);
    expect(w.OR).toContainEqual({ userId: null, workItem: { projectId: { in: [3n, 9n] } } });
  });

  /**
   * ข้อมูลที่ไม่ครบต้องแปลว่าไม่มีสิทธิ์ (§9) — คนที่ยังไม่มีโปรเจกต์ไหนเลย
   * ต้องได้เฉพาะแถวที่จ่าหน้าถึงตัวเอง ไม่ใช่ได้ทุกแถวเพราะรายการว่าง
   */
  it('**ไม่มีโปรเจกต์ที่เห็นได้เลย — ไม่มีแถวระดับทีมสักแถว**', () => {
    const w = inboxAudience(ME, []);
    expect(w.OR).toEqual([{ userId: ME }]);
  });

  /**
   * แถวระดับทีมที่ไม่ผูกกับงาน ตอบไม่ได้ว่าเป็นของโปรเจกต์ไหน จึงตอบไม่ได้ว่า
   * ใครควรเห็น · วันนี้ไม่มีโค้ดไหนสร้างแถวแบบนั้น และนั่นคือเหตุผลที่ต้อง
   * ปิดไว้ตั้งแต่ตอนนี้ — ไม่ใช่รอให้มีคนสร้างแล้วค่อยพบว่ามันหลุดถึงทุกคน
   * (§8 "กลไกที่ปลอดภัยเพราะยังไม่มีใครเข้าถึงได้")
   */
  it('**แถวระดับทีมที่ไม่ผูกกับงาน ไม่ถึงใครเลย**', () => {
    const w = inboxAudience(ME, [1n]);
    const team = w.OR.find((c) => c.userId === null);
    expect(team?.workItem).toBeDefined();
  });

  /** ผู้เยี่ยมชมที่ยังไม่ล็อกอิน ไม่มีกล่องแจ้งเตือน — ไม่ใช่มีกล่องที่เห็นทุกอย่าง */
  it('**ไม่ได้ล็อกอิน — ไม่มีเงื่อนไขไหนตรงเลย**', () => {
    const w = inboxAudience(null, [1n, 2n]);
    expect(w.OR).toEqual([]);
  });

  /**
   * เดิมเคสนี้เขียนว่า "ไม่แก้อาร์เรย์ที่รับเข้ามา" ซึ่ง **ไม่มีทางแดง** —
   * ฟังก์ชันไม่มีบรรทัดไหนแก้อาร์เรย์อยู่แล้ว ลบ `[...]` ออกก็ยังเขียว
   * (ตอนพิสูจน์ว่าเทสต์แดงได้ จับได้ตรงนี้) · สิ่งที่ `[...]` ทำจริงคือ
   * ตัดสายจากอาร์เรย์ของผู้เรียก เพื่อให้เงื่อนไขที่คืนไปแล้วไม่เปลี่ยนตาม
   * เมื่อผู้เรียกไปแก้ของตัวเองต่อ · เคสนี้จึงวัดสิ่งนั้นแทน
   */
  it('**รายการโปรเจกต์ที่คืนออกไปเป็นสำเนา ไม่ใช่ตัวเดิมของผู้เรียก**', () => {
    const ids = [1n, 2n];
    const w = inboxAudience(ME, ids);
    const team = w.OR.find((c) => c.userId === null);
    expect(team?.workItem?.projectId.in).toEqual(ids);
    expect(team?.workItem?.projectId.in).not.toBe(ids);
  });
});
