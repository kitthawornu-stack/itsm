/**
 * ข้อกำหนดของสถิติเวลาตอบสนอง — **เขียนก่อนโค้ด**
 *
 * ## ทำไมต้องมีไฟล์นี้
 *
 * เอกสารสถานะเขียนไว้เองว่า **"ยังไม่เคยวัดโหลดจริงเลยสักครั้ง"** ·
 * ก่อนจะวัดได้ ต้องมีตัวคิดเลขที่เชื่อได้ก่อน — **p95 คำนวณผิดง่ายมาก
 * และผิดแบบเงียบ** เพราะตัวเลขที่ได้ยังดูเหมือนตัวเลขที่ถูก
 *
 * ## สิ่งที่ผิดแล้วเงียบ
 *
 *   1. **นับคำขอที่ล้มรวมไปกับเวลา** — 500 ที่ตอบกลับใน 2 มิลลิวินาที
 *      จะดึง p95 ลงจนระบบดูเร็วขึ้นตอนที่มันกำลังพัง
 *   2. **รายงาน p95 จากตัวอย่างสามตัว** — ตัวเลขที่อ่านเหมือนข้อเท็จจริง
 *      แต่ไม่มีอะไรรองรับ · ต้องบอกจำนวนตัวอย่างเสมอ
 *   3. **ดัชนีเพี้ยนไปหนึ่ง** — p100 ที่หลุดออกนอกอาร์เรย์ หรือ p50 ที่
 *      ได้ค่าของตัวถัดไป · ผิดนิดเดียวแต่ทุกตัวเลขที่รายงานไปแล้วผิดตาม
 */
import { describe, expect, it } from 'vitest';

import { percentile, summarize, type Sample } from './latency-stats';

const ok = (ms: number): Sample => ({ ms, ok: true });
const fail = (ms: number): Sample => ({ ms, ok: false });

// ============================================================

describe('สถิติเวลาตอบสนอง · A · เปอร์เซ็นไทล์', () => {
  /**
   * ใช้วิธี nearest-rank — ค่าที่คืนต้องเป็น **ค่าที่วัดได้จริง** เสมอ
   * ไม่ใช่ค่าที่ประมาณขึ้นมาระหว่างสองตัว · ตัวเลขที่ไม่เคยเกิดขึ้นจริง
   * อธิบายให้คนที่กำลังไล่ปัญหาไม่ได้
   */
  it('คืนค่าที่วัดได้จริงเสมอ ไม่ใช่ค่าเฉลี่ยระหว่างสองตัว', () => {
    const xs = [10, 20, 30, 40];
    expect(xs).toContain(percentile(xs, 50));
    expect(xs).toContain(percentile(xs, 95));
  });

  it('ตัวอย่างเดียว ทุกเปอร์เซ็นไทล์ได้ค่าเดียวกัน', () => {
    expect(percentile([7], 50)).toBe(7);
    expect(percentile([7], 99)).toBe(7);
  });

  it('**p100 ได้ค่าสูงสุด ไม่หลุดออกนอกอาร์เรย์**', () => {
    expect(percentile([1, 2, 3, 4, 5], 100)).toBe(5);
  });

  it('p0 ได้ค่าต่ำสุด', () => {
    expect(percentile([5, 1, 3], 0)).toBe(1);
  });

  /**
   * **`ceil` ไม่ใช่ `floor`**
   *
   * ทั้งสองให้ผลเหมือนกันเมื่อ p/100 × N ลงตัวพอดี ซึ่งเป็นกรณีที่คนมักทดสอบ
   * (เช่น p50 ของร้อยค่า) · ต่างกันทันทีเมื่อไม่ลงตัว — p50 ของสามค่า
   * ได้ค่ากลาง ส่วน `floor` จะได้ค่าต่ำสุด · เดิมไม่มีเคสนี้ เปลี่ยนเป็น
   * `floor` แล้วยังเขียวทั้งชุด
   */
  it('**p50 ของสามค่า ได้ค่ากลาง ไม่ใช่ค่าต่ำสุด**', () => {
    expect(percentile([10, 20, 30], 50)).toBe(20);
    expect(percentile([10, 20, 30, 40, 50], 30)).toBe(20);
  });

  /**
   * ค่านอกช่วงถูกบีบที่ทางเข้า — ผู้เรียกที่ส่ง 101 มาต้องได้ค่าสูงสุด
   * ไม่ใช่ `undefined` ที่ถูกแปลงเป็นตัวเลขต่อไปเงียบ ๆ
   */
  it('**เปอร์เซ็นต์นอกช่วง 0–100 ถูกบีบ ไม่หลุดออกนอกอาร์เรย์**', () => {
    expect(percentile([1, 2, 3], 150)).toBe(3);
    expect(percentile([1, 2, 3], -20)).toBe(1);
  });

  /** ค่าที่ยังไม่เรียงต้องได้ผลเดียวกับที่เรียงแล้ว */
  it('เรียงให้เองก่อนคิด', () => {
    expect(percentile([30, 10, 40, 20], 50)).toBe(percentile([10, 20, 30, 40], 50));
  });

  it('**ไม่แก้อาร์เรย์ที่รับเข้ามา**', () => {
    const xs = [30, 10, 20];
    percentile(xs, 50);
    expect(xs).toEqual([30, 10, 20]);
  });

  /** ไม่มีตัวอย่างเลย ตอบไม่ได้ — `null` ไม่ใช่ศูนย์ ซึ่งอ่านเหมือน "เร็วมาก" */
  it('**ไม่มีตัวอย่างเลย คืน `null` ไม่ใช่ 0**', () => {
    expect(percentile([], 95)).toBeNull();
  });

  /** ตัวอย่างจริงที่ตรวจด้วยมือได้: 100 ค่า 1..100 · p95 คือค่าที่ 95 */
  it('ตรวจกับชุดที่นับด้วยมือได้', () => {
    const xs = Array.from({ length: 100 }, (_, i) => i + 1);
    expect(percentile(xs, 50)).toBe(50);
    expect(percentile(xs, 95)).toBe(95);
    expect(percentile(xs, 99)).toBe(99);
  });
});

